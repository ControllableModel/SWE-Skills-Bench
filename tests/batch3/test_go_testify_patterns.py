"""
Test for 'go-testify-patterns' skill (variant ext3) — Human-Readable Byte-Size
Formatter for the Terraform output-format package (hashicorp/terraform).

The agent must add a deterministic, I/O-free `HumanByteSize(n int64) string`
helper to the existing `format` package:
  - internal/command/format/bytesize.go      (new, package format)
  - internal/command/format/bytesize_test.go (new, testify-based, package format)

`HumanByteSize` renders a byte count using binary (1024-based) units
(B, KiB, MiB, GiB, TiB, PiB):
  - n < 1024            -> "<n> B"          (e.g. 0 -> "0 B", 1023 -> "1023 B")
  - n >= 1024           -> "<x.xx> <unit>"  with exactly two decimals, scaled
                           into the largest unit for which value >= 1
  - rounding            -> half-away-from-zero to two decimals
  - negative inputs     -> leading '-' on the formatted magnitude
  - values beyond PiB   -> still use the PiB unit (no overflow to a missing unit)

Verification strategy (discriminative power):
Rather than trusting the agent's own bytesize_test.go, most L2 cases inject an
INDEPENDENT Go test file (`zz_bench_bytesize_test.go`) into the format package
that calls `HumanByteSize` directly and deep-validates the exact rendered
strings for the documented boundary, rounding, negative and overflow cases.
That file is removed in teardown. A naive implementation (decimal/1000-based
units, wrong/variable decimal count, truncation instead of rounding, dropping
the sign, or overflowing past PiB) cannot pass these checks. Finally the agent's
own mandated command (`go test ./internal/command/format/ -run TestHumanByteSize
-v`) is driven to confirm the delivered testify test exists and passes.
"""

