DRIVER_SOURCE = r'''// Code generated by the benchmark harness. DO NOT EDIT. Removed after the run.
package format

import (
	"fmt"
	"testing"
)

// check is a tiny assertion helper local to the driver.
func benchExpect(t *testing.T, in int64, want string) {
	got := HumanByteSize(in)
	if got != want {
		t.Fatalf("HumanByteSize(%d) = %q, want %q", in, got, want)
	}
}

// Raw-bytes branch: n < 1024 renders an integer count + " B".
func TestBenchRawBytesBranch(t *testing.T) {
	benchExpect(t, 0, "0 B")
	benchExpect(t, 1, "1 B")
	benchExpect(t, 512, "512 B")
	benchExpect(t, 1023, "1023 B")
	fmt.Println("BENCH_OK_raw_bytes")
}

// Exact unit boundaries render "1.00 <unit>" with binary (1024) factors.
func TestBenchUnitBoundaries(t *testing.T) {
	benchExpect(t, 1024, "1.00 KiB")
	benchExpect(t, 1048576, "1.00 MiB")
	benchExpect(t, 1073741824, "1.00 GiB")
	benchExpect(t, 1099511627776, "1.00 TiB")
	fmt.Println("BENCH_OK_boundaries")
}

// Two-decimal rendering for non-exact scaled values.
func TestBenchTwoDecimals(t *testing.T) {
	benchExpect(t, 1536, "1.50 KiB")       // 1.5 KiB exactly
	benchExpect(t, 2621440, "2.50 MiB")    // doc: 2_621_440 -> 2.50 MiB
	fmt.Println("BENCH_OK_two_decimals")
}

// Rounding is half-away-from-zero to two decimals (NOT truncation).
func TestBenchRounding(t *testing.T) {
	// 1127 bytes = 1.1005859375 KiB -> "1.10 KiB" per the doc.
	benchExpect(t, 1127, "1.10 KiB")
	// A value whose third decimal forces round-up, distinguishing rounding
	// from truncation: 1126 bytes = 1.099609375 KiB -> rounds to 1.10 KiB,
	// truncation would give 1.09 KiB.
	got := HumanByteSize(1126)
	if got == "1.09 KiB" {
		t.Fatalf("HumanByteSize(1126) = %q looks truncated; expected rounding to 1.10 KiB", got)
	}
	benchExpect(t, 1126, "1.10 KiB")
	fmt.Println("BENCH_OK_rounding")
}

// Negative inputs: leading '-' on the formatted magnitude, both branches.
func TestBenchNegative(t *testing.T) {
	benchExpect(t, -100, "-100 B")     // raw-bytes branch
	benchExpect(t, -2048, "-2.00 KiB") // scaled branch
	benchExpect(t, -1023, "-1023 B")
	benchExpect(t, -1024, "-1.00 KiB")
	fmt.Println("BENCH_OK_negative")
}

// Each unit step is exactly a factor of 1024 (binary, not 1000-based decimal).
func TestBenchBinaryFactors(t *testing.T) {
	// If the impl used 1000-based units, 1000 would render as "1.00 KiB"
	// (or "1.00 KB"); per spec 1000 < 1024 must stay raw bytes.
	benchExpect(t, 1000, "1000 B")
	// 1024*1024 must be MiB, not "1024.00 KiB".
	benchExpect(t, 1048576, "1.00 MiB")
	// 1023 KiB worth of bytes stays in KiB (just under 1 MiB).
	benchExpect(t, 1024*1024-1024, "1023.00 KiB")
	fmt.Println("BENCH_OK_binary_factors")
}

// Values beyond PiB still render with the PiB unit (no missing/overflow unit).
func TestBenchPiBOverflow(t *testing.T) {
	const pib = int64(1) << 50 // 1024^5
	benchExpect(t, pib, "1.00 PiB")
	// A value well beyond PiB: 4096 PiB stays PiB (would be "4 EiB" if it
	// overflowed past the largest defined unit).
	huge := int64(4096) * pib
	got := HumanByteSize(huge)
	if got != "4096.00 PiB" {
		t.Fatalf("HumanByteSize(%d) = %q, want %q (must clamp to PiB)", huge, got, "4096.00 PiB")
	}
	// max int64 must also clamp to a PiB rendering and not panic.
	maxGot := HumanByteSize(9223372036854775807)
	if len(maxGot) < 4 || maxGot[len(maxGot)-3:] != "PiB" {
		t.Fatalf("HumanByteSize(maxint64) = %q, expected to end in PiB", maxGot)
	}
	fmt.Println("BENCH_OK_pib_overflow")
}

// Format shape: scaled outputs always have exactly two decimals and a single
// space before the unit; raw outputs have no decimal point.
func TestBenchFormatShape(t *testing.T) {
	scaled := HumanByteSize(1536)
	// "1.50 KiB": exactly one '.', two chars after it before the space.
	dot := -1
	sp := -1
	for i := 0; i < len(scaled); i++ {
		if scaled[i] == '.' {
			dot = i
		}
		if scaled[i] == ' ' {
			sp = i
			break
		}
	}
	if dot < 0 || sp < 0 || sp-dot != 3 {
		t.Fatalf("scaled output %q must have exactly two decimal places before the space", scaled)
	}
	raw := HumanByteSize(42)
	for i := 0; i < len(raw); i++ {
		if raw[i] == '.' {
			t.Fatalf("raw-bytes output %q must not contain a decimal point", raw)
		}
	}
	if raw != "42 B" {
		t.Fatalf("HumanByteSize(42) = %q, want %q", raw, "42 B")
	}
	fmt.Println("BENCH_OK_format_shape")
}

// Determinism: identical input yields identical output across calls.
func TestBenchDeterministic(t *testing.T) {
	for _, v := range []int64{0, 1023, 1024, 1536, 2621440, -2048, int64(1) << 50} {
		a := HumanByteSize(v)
		b := HumanByteSize(v)
		if a != b {
			t.Fatalf("non-deterministic output for %d: %q vs %q", v, a, b)
		}
	}
	fmt.Println("BENCH_OK_deterministic")
}
'''


def _write_driver():
    with open(DRIVER_PATH, "w") as f:
        f.write(DRIVER_SOURCE)


def _remove_driver():
    try:
        os.remove(DRIVER_PATH)
    except OSError:
        pass


@pytest.fixture(scope="module", autouse=True)
def _warmup_go_modules():
    """Pre-fetch module deps once so per-test native commands don't re-download."""
    if os.path.isdir(FORMAT_DIR):
        try:
            _run_go(["mod", "download"], timeout=600)
        except Exception:
            pass
    yield


@pytest.fixture(scope="module")
def driver_run():
    """
    Build & run the independent benchmark driver once for the module.
    Returns the CompletedProcess so individual tests can assert on markers.
    """
    assert os.path.isdir(FORMAT_DIR), f"format package dir missing: {FORMAT_DIR}"
    assert os.path.isfile(BYTESIZE_GO), "bytesize.go was not created by the agent"

    _write_driver()
    try:
        proc = _run_go(
            ["test", "-run", "TestBench", "-v", "-count=1", "-timeout=120s", "./"],
            timeout=600,
        )
    finally:
        _remove_driver()
    return proc


def _assert_marker(proc, marker):
    combined = (proc.stdout or "") + "\n" + (proc.stderr or "")
    assert proc.returncode == 0, (
        f"benchmark driver `go test` failed (rc={proc.returncode}).\n"
        f"STDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )
    assert marker in combined, (
        f"expected marker {marker!r} not found in driver output.\n"
        f"STDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )


