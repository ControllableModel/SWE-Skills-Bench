"""Tests for the `grpc-service-definition` skill (variant ext3).

Skill / task: Strengthen put-request validation in etcd's v3 KV service.

The single guard `checkPutRequest` (in
`server/etcdserver/api/v3rpc/key.go`) gates every mutating `Put` RPC. The
variant task hardens it so that, in addition to the pre-existing checks, a
*negative* `Lease` identifier is turned away with the malformed-input
classification (`rpctypes.ErrGRPCEmptyKey`, gRPC `InvalidArgument`), while the
established behaviors are preserved exactly:

  * empty key                          -> empty-key error (highest precedence);
  * IgnoreValue=true + non-empty Value -> value-provided error;
  * IgnoreLease=true + non-zero Lease  -> lease-provided error;
  * Lease < 0                          -> malformed-input (empty-key) error;
  * a fully valid put (non-empty key, no contradictions, Lease >= 0) -> nil.

The agent must also add a `TestCheckPutRequest` to `key_test.go`.

Verification strategy
---------------------
L1 checks the deliverable files exist and are minimally well-formed (the guard
and the new test are present).

L2 drives the repo's native Go toolchain. The discriminative L2 cases do NOT
trust the test the agent itself wrote: this module installs an *independent*
probe (`zz_skillprobe_test.go`) into the `v3rpc` package. Because it lives in
`package v3rpc` it can call the unexported `checkPutRequest` directly and
deep-validate, for every requirement, the returned error's identity and its
gRPC status code. A naive solution that leaves `checkPutRequest` unchanged
(so a negative lease is silently accepted), that reorders the empty-key check,
or that returns an opaque/plain error instead of the specific `rpctypes`
classification, fails these probes.
"""

import os
import subprocess
import textwrap

import pytest

def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/etcd")
PKG_REL = "etcdserver/api/v3rpc"
SERVER_DIR = os.path.join(REPO_DIR, "server")
PKG_DIR = os.path.join(SERVER_DIR, PKG_REL)
KEY_GO = os.path.join(PKG_DIR, "key.go")
KEY_TEST_GO = os.path.join(PKG_DIR, "key_test.go")

PROBE_BASENAME = "zz_skillprobe_test.go"
PROBE_PATH = os.path.join(PKG_DIR, PROBE_BASENAME)

GO_ENV = {
    **os.environ,
    "GOFLAGS": os.environ.get("GOFLAGS", ""),
    "CGO_ENABLED": "0",
}


def _go(args, timeout=600):
    """Run a `go` command from the server module dir."""
    return subprocess.run(
        ["go"] + args,
        cwd=SERVER_DIR,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=GO_ENV,
    )


# --------------------------------------------------------------------------
# Independent probe test installed into the package.
#
# It lives in `package v3rpc` so it can call the unexported `checkPutRequest`
# directly with hand-built `*pb.PutRequest` values. Each requirement is a hard
# assertion; the whole thing must compile AND pass.
#
# Key discriminators against a naive / unchanged implementation:
#   * negative-lease rejection (the new behavior) -- baseline accepts it;
#   * the rejection must be the SPECIFIC empty-key classification, not some
#     other / opaque error;
#   * empty-key precedence over the negative-lease and contradiction checks;
#   * every accepted case really returns nil;
#   * the returned errors carry the right gRPC status code (InvalidArgument).
# --------------------------------------------------------------------------
PROBE_SOURCE = textwrap.dedent(
    '''\
    // Code generated by the skill benchmark. DO NOT keep.
    package v3rpc

    import (
    	stderrors "errors"
    	"testing"

    	"google.golang.org/grpc/codes"
    	"google.golang.org/grpc/status"

    	pb "go.etcd.io/etcd/api/v3/etcdserverpb"
    	"go.etcd.io/etcd/api/v3/v3rpc/rpctypes"
    )

    func skillProbeCodeOf(err error) codes.Code {
    	if err == nil {
    		return codes.OK
    	}
    	st, ok := status.FromError(err)
    	if !ok {
    		return codes.Unknown
    	}
    	return st.Code()
    }

    func skillProbeSameErr(got, want error) bool {
    	if got == nil || want == nil {
    		return got == want
    	}
    	return got == want || got.Error() == want.Error() || stderrors.Is(got, want)
    }

    // SKILLPROBE 0: a fully valid put must be accepted (nil).
    func TestSkillProbe_ValidPutAccepted(t *testing.T) {
    	r := &pb.PutRequest{Key: []byte("k"), Value: []byte("v"), Lease: 3}
    	if got := checkPutRequest(r); got != nil {
    		t.Fatalf("valid put rejected: got %v, want nil", got)
    	}
    	// Lease == 0 (no lease) and a positive lease are both fine.
    	if got := checkPutRequest(&pb.PutRequest{Key: []byte("k"), Lease: 0}); got != nil {
    		t.Fatalf("put with Lease=0 rejected: got %v, want nil", got)
    	}
    	if got := checkPutRequest(&pb.PutRequest{Key: []byte("k"), Lease: 1 << 40}); got != nil {
    		t.Fatalf("put with large positive lease rejected: got %v, want nil", got)
    	}
    }

    // SKILLPROBE 1: empty key must be rejected with the empty-key error.
    func TestSkillProbe_EmptyKey(t *testing.T) {
    	got := checkPutRequest(&pb.PutRequest{Key: nil})
    	if !skillProbeSameErr(got, rpctypes.ErrGRPCEmptyKey) {
    		t.Fatalf("empty key -> %v, want ErrGRPCEmptyKey", got)
    	}
    	if skillProbeCodeOf(got) != codes.InvalidArgument {
    		t.Fatalf("empty key code = %v, want InvalidArgument", skillProbeCodeOf(got))
    	}
    }

    // SKILLPROBE 2: IgnoreValue contradiction is detected; an empty Value with
    // IgnoreValue is fine.
    func TestSkillProbe_IgnoreValueContradiction(t *testing.T) {
    	bad := checkPutRequest(&pb.PutRequest{Key: []byte("k"), IgnoreValue: true, Value: []byte("x")})
    	if !skillProbeSameErr(bad, rpctypes.ErrGRPCValueProvided) {
    		t.Fatalf("IgnoreValue+Value -> %v, want ErrGRPCValueProvided", bad)
    	}
    	ok := checkPutRequest(&pb.PutRequest{Key: []byte("k"), IgnoreValue: true})
    	if ok != nil {
    		t.Fatalf("IgnoreValue with empty Value -> %v, want nil", ok)
    	}
    }

    // SKILLPROBE 3: IgnoreLease contradiction is detected; Lease==0 with
    // IgnoreLease is fine.
    func TestSkillProbe_IgnoreLeaseContradiction(t *testing.T) {
    	bad := checkPutRequest(&pb.PutRequest{Key: []byte("k"), IgnoreLease: true, Lease: 7})
    	if !skillProbeSameErr(bad, rpctypes.ErrGRPCLeaseProvided) {
    		t.Fatalf("IgnoreLease+Lease -> %v, want ErrGRPCLeaseProvided", bad)
    	}
    	ok := checkPutRequest(&pb.PutRequest{Key: []byte("k"), IgnoreLease: true, Lease: 0})
    	if ok != nil {
    		t.Fatalf("IgnoreLease with Lease=0 -> %v, want nil", ok)
    	}
    }

    // SKILLPROBE 4 (THE NEW BEHAVIOR): a negative lease must be rejected with the
    // malformed-input classification -- the SAME error used for an empty key.
    // A baseline checkPutRequest that was never hardened ACCEPTS this and so
    // fails here.
    func TestSkillProbe_NegativeLeaseRejected(t *testing.T) {
    	for _, lease := range []int64{-1, -2, -1 << 40} {
    		got := checkPutRequest(&pb.PutRequest{Key: []byte("k"), Lease: lease})
    		if got == nil {
    			t.Fatalf("negative lease %d was ACCEPTED; want rejection", lease)
    		}
    		if !skillProbeSameErr(got, rpctypes.ErrGRPCEmptyKey) {
    			t.Fatalf("negative lease %d -> %v, want malformed-input (ErrGRPCEmptyKey)", lease, got)
    		}
    		if skillProbeCodeOf(got) != codes.InvalidArgument {
    			t.Fatalf("negative lease %d code = %v, want InvalidArgument", lease, skillProbeCodeOf(got))
    		}
    		// It must NOT be misclassified as value/lease-provided.
    		if skillProbeSameErr(got, rpctypes.ErrGRPCLeaseProvided) ||
    			skillProbeSameErr(got, rpctypes.ErrGRPCValueProvided) {
    			t.Fatalf("negative lease %d misclassified as provided-error: %v", lease, got)
    		}
    	}
    }

    // SKILLPROBE 5: the empty-key check takes precedence over everything else.
    // Even a request that is ALSO wrong in other ways (negative lease, ignore
    // contradictions) must surface as the empty-key error.
    func TestSkillProbe_EmptyKeyPrecedence(t *testing.T) {
    	cases := []*pb.PutRequest{
    		{Key: nil, Lease: -1},
    		{Key: []byte{}, IgnoreValue: true, Value: []byte("x")},
    		{Key: nil, IgnoreLease: true, Lease: 9},
    		{Key: nil, IgnoreValue: true, Value: []byte("x"), IgnoreLease: true, Lease: -5},
    	}
    	for i, r := range cases {
    		got := checkPutRequest(r)
    		if !skillProbeSameErr(got, rpctypes.ErrGRPCEmptyKey) {
    			t.Fatalf("case %d: empty key did not take precedence: got %v, want ErrGRPCEmptyKey", i, got)
    		}
    	}
    }

    // SKILLPROBE 6: a negative lease that is ALSO contradictory with IgnoreLease
    // is still rejected (any rejection that is a real rpctypes classification is
    // acceptable here); the point is it is never accepted.
    func TestSkillProbe_NegativeLeaseNeverAccepted(t *testing.T) {
    	got := checkPutRequest(&pb.PutRequest{Key: []byte("k"), IgnoreLease: true, Lease: -3})
    	if got == nil {
    		t.Fatalf("contradictory negative lease was accepted; want rejection")
    	}
    	if skillProbeCodeOf(got) != codes.InvalidArgument {
    		t.Fatalf("rejection code = %v, want InvalidArgument", skillProbeCodeOf(got))
    	}
    }
    '''
)


@pytest.fixture(scope="module", autouse=True)
def _install_probe_and_cleanup():
    """Install the independent probe test into the package, remove afterwards."""
    assert os.path.isdir(PKG_DIR), f"package dir missing: {PKG_DIR}"
    with open(PROBE_PATH, "w") as fh:
        fh.write(PROBE_SOURCE)
    try:
        yield
    finally:
        try:
            os.remove(PROBE_PATH)
        except OSError:
            pass


class TestGrpcServiceDefinition:
    REPO_DIR = _find_repo_dir("/workspace/etcd")

    # ---------------------- L1: deliverables exist / well-formed -------------

    def test_key_go_exists(self):
        """L1: the guard source file `key.go` exists."""
        assert os.path.isfile(KEY_GO), f"missing {KEY_GO}"

    def test_key_test_go_exists(self):
        """L1: the test file `key_test.go` exists."""
        assert os.path.isfile(KEY_TEST_GO), f"missing {KEY_TEST_GO}"

    def test_key_go_defines_checkputrequest(self):
        """L1: `key.go` still defines `checkPutRequest` and references the lease field."""
        with open(KEY_GO) as fh:
            src = fh.read()
        assert "func checkPutRequest(" in src, "checkPutRequest function definition not found"
        assert ".Lease" in src, "checkPutRequest no longer references the Lease field"

    def test_key_test_defines_checkputrequest_test(self):
        """L1: `key_test.go` adds a TestCheckPutRequest exercising the guard."""
        with open(KEY_TEST_GO) as fh:
            src = fh.read()
        assert "func TestCheckPutRequest(" in src, "TestCheckPutRequest not found in key_test.go"
        assert "checkPutRequest(" in src, "TestCheckPutRequest does not call checkPutRequest"

    # ---------------------- L2: native build + behavior ----------------------

    def test_package_builds(self):
        """L2: the v3rpc package compiles (agent did not break the build)."""
        res = _go(["build", "./" + PKG_REL + "/..."])
        assert res.returncode == 0, (
            "go build failed:\n" + res.stdout + "\n" + res.stderr
        )

    def test_vet_package(self):
        """L2: `go vet` passes on the package when it is able to run."""
        res = _go(["vet", "./" + PKG_REL + "/"])
        if res.returncode != 0:
            combined = (res.stdout + res.stderr).lower()
            if (
                "cannot find" not in combined
                and "timeout" not in combined
                and "dial tcp" not in combined
                and "no such host" not in combined
            ):
                assert res.returncode == 0, (
                    "go vet reported problems:\n" + res.stdout + "\n" + res.stderr
                )

    def test_existing_checkrange_passes(self):
        """L2: the pre-existing TestCheckRangeRequest must still pass (no regression)."""
        res = _go(
            ["test", "./" + PKG_REL + "/", "-run", "^TestCheckRangeRequest$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, "TestCheckRangeRequest failed:\n" + out
        assert "PASS" in out, "no PASS marker:\n" + out
        assert "--- FAIL" not in out, "a subtest FAILED:\n" + out

    def test_agent_checkputrequest_passes(self):
        """L2: the agent's own TestCheckPutRequest (the native acceptance cmd) passes."""
        res = _go(
            ["test", "./" + PKG_REL + "/", "-run", "^TestCheckPutRequest$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "native acceptance command (TestCheckPutRequest) failed:\n" + out
        )
        assert "PASS" in out, "no PASS marker:\n" + out
        assert "--- FAIL" not in out, "a subtest FAILED:\n" + out

    def test_probe_valid_put_accepted(self):
        """L2: an independent probe confirms valid puts (incl. Lease>=0) are accepted."""
        res = _go(
            ["test", "./" + PKG_REL + "/", "-run", "^TestSkillProbe_ValidPutAccepted$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, "valid-put probe failed:\n" + out
        assert "--- FAIL" not in out, out

    def test_probe_existing_classifications_preserved(self):
        """L2: empty-key / IgnoreValue / IgnoreLease classifications are preserved."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillProbe_EmptyKey|TestSkillProbe_IgnoreValueContradiction|TestSkillProbe_IgnoreLeaseContradiction)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "existing-classification probe failed (a pre-existing check regressed):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_negative_lease_rejected(self):
        """L2: THE NEW BEHAVIOR -- a negative lease is rejected as malformed-input.

        A naive/unchanged checkPutRequest accepts negative leases and so fails here.
        """
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillProbe_NegativeLeaseRejected|TestSkillProbe_NegativeLeaseNeverAccepted)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "negative-lease probe failed (the guard does not reject a negative "
            "Lease with the malformed-input/empty-key classification):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_empty_key_precedence(self):
        """L2: the empty-key check takes precedence over all other rejections."""
        res = _go(
            ["test", "./" + PKG_REL + "/", "-run", "^TestSkillProbe_EmptyKeyPrecedence$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "empty-key precedence probe failed (empty key did not win over other "
            "contradictions):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_full_probe_suite_and_existing_pass_together(self):
        """L2: the whole behavior matrix passes in one native run (integration)."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestCheckRangeRequest|TestCheckPutRequest|TestSkillProbe_.*)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "combined existing + probe suite failed:\n" + out
        )
        assert "--- FAIL" not in out, "at least one case FAILED:\n" + out
        assert "ok  " in out or "PASS" in out, "no success marker:\n" + out
