"""Tests for the `grpc-service-definition` skill (variant ext7).

Skill / task: Pin down the server-to-client error conversion in etcd's
`api/v3rpc/rpctypes` package. The package's `Error` function converts a
server-side transport (gRPC status) error into a client-side `EtcdError`
(exposing a stable classification `Code()` and a human-readable description),
and `ErrorDesc` extracts the description from any error.

The variant requires a new test (`TestErrorConversion`) in
`api/v3rpc/rpctypes/error_test.go` that asserts:

  * Round-trip for known server-side errors: `Error(serverErr)` yields an
    `EtcdError` whose `Code()` equals the server error's code and whose
    description equals the server error's description -- exercised for at
    least one invalid-argument, one not-found and one resource-exhausted
    error.
  * Pass-through for unknown errors: `Error(errors.New("x"))` returns that
    very error back, NOT coerced into an `EtcdError`, description preserved.
  * `Error(nil)` returns `nil`.
  * `ErrorDesc` returns the transport message for a transport error and the
    plain `.Error()` string for a non-transport error; and
    `ErrorDesc(serverErr) == ErrorDesc(Error(serverErr))` for known errors.
  * The lookup of known errors goes through the package's description-keyed
    table, not arbitrary external string comparison.
  * All existing tests (including `TestConvert`) keep passing.

Native acceptance command (run from the repo root):

    cd api && go test ./v3rpc/rpctypes/ -run 'TestErrorConversion|TestConvert' -count=1 -v

Verification strategy
---------------------
L1 checks the deliverable files exist and are minimally well-formed
(the package still defines `Error`, `ErrorDesc`, `EtcdError`, and
`error_test.go` adds a `TestErrorConversion`).

L2 drives the repo's native Go toolchain from the `api` module. The
discriminative L2 cases do NOT trust the test the agent itself may have
written: this module installs an *independent* probe test
(`zz_skillprobe_test.go`) into the `rpctypes` package. Because the probe
lives in `package rpctypes` it can reach the unexported description-keyed
`errStringToError` table and the `EtcdError` struct directly, and it
deep-validates the converted code, the converted description, the unchanged
pass-through identity, the nil case and the `ErrorDesc` equalities. A naive
solution (returning a fixed value, coercing unknown errors into `EtcdError`,
dropping the description, mishandling nil, or hard-coding string comparisons)
fails these probes.
"""

import os
import subprocess
import textwrap

import pytest

def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/etcd")
API_DIR = os.path.join(REPO_DIR, "api")
PKG_REL = "v3rpc/rpctypes"
PKG_DIR = os.path.join(API_DIR, "v3rpc", "rpctypes")
ERROR_GO = os.path.join(PKG_DIR, "error.go")
ERROR_TEST_GO = os.path.join(PKG_DIR, "error_test.go")

PROBE_BASENAME = "zz_skillprobe_test.go"
PROBE_PATH = os.path.join(PKG_DIR, PROBE_BASENAME)

GO_ENV = {
    **os.environ,
    "GOFLAGS": os.environ.get("GOFLAGS", ""),
    "CGO_ENABLED": "0",
}


def _go(args, timeout=600):
    """Run a `go` command from the `api` module dir (where tests run)."""
    return subprocess.run(
        ["go"] + args,
        cwd=API_DIR,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=GO_ENV,
    )


# --------------------------------------------------------------------------
# Independent probe test installed into the package.
#
# It lives in `package rpctypes` so it can reach the unexported
# description-keyed table `errStringToError` and the `EtcdError` struct.
# Each requirement is a hard assertion; the whole thing must compile AND pass.
# --------------------------------------------------------------------------
PROBE_SOURCE = textwrap.dedent(
    '''\
    // Code generated by the skill benchmark. DO NOT keep.
    package rpctypes

    import (
    	stderrors "errors"
    	"testing"

    	"google.golang.org/grpc/codes"
    	"google.golang.org/grpc/status"
    )

    // skillProbeCode pulls the classification code out of any error the way a
    // client would: prefer the EtcdError.Code(), else fall back to the status.
    func skillProbeCode(t *testing.T, err error) codes.Code {
    	t.Helper()
    	if err == nil {
    		return codes.OK
    	}
    	var ee EtcdError
    	if stderrors.As(err, &ee) {
    		return ee.Code()
    	}
    	if st, ok := status.FromError(err); ok {
    		return st.Code()
    	}
    	return codes.Unknown
    }

    // SKILLPROBE 1: round-trip conversion for KNOWN server-side errors.
    // For a representative invalid-argument, not-found and resource-exhausted
    // server error, Error(serverErr) must be an EtcdError whose Code() equals
    // the server code and whose description equals the server description.
    func TestSkillProbe_RoundTripKnownErrors(t *testing.T) {
    	cases := []struct {
    		name   string
    		server error
    		code   codes.Code
    	}{
    		{"invalid-argument", ErrGRPCEmptyKey, codes.InvalidArgument},
    		{"not-found", ErrGRPCMemberNotFound, codes.NotFound},
    		{"resource-exhausted", ErrGRPCNoSpace, codes.ResourceExhausted},
    		// a second invalid-argument to make sure it is not a 1-off hardcode.
    		{"invalid-argument-2", ErrGRPCKeyNotFound, codes.InvalidArgument},
    		// an out-of-range one for breadth.
    		{"out-of-range", ErrGRPCCompacted, codes.OutOfRange},
    	}
    	for _, c := range cases {
    		got := Error(c.server)
    		var ee EtcdError
    		if !stderrors.As(got, &ee) {
    			t.Fatalf("%s: Error(serverErr) = %T (%v), want EtcdError", c.name, got, got)
    		}
    		if ee.Code() != c.code {
    			t.Fatalf("%s: converted Code() = %v, want %v", c.name, ee.Code(), c.code)
    		}
    		serverDesc := ErrorDesc(c.server)
    		if ee.Error() != serverDesc {
    			t.Fatalf("%s: converted desc = %q, want %q", c.name, ee.Error(), serverDesc)
    		}
    		// The source server status really carries the same code we assert.
    		if st, ok := status.FromError(c.server); ok && st.Code() != c.code {
    			t.Fatalf("%s: baseline server code = %v, want %v", c.name, st.Code(), c.code)
    		}
    	}
    }

    // SKILLPROBE 2: pass-through for UNKNOWN errors. A plain errors.New(...) is
    // not in the package table, so Error must return it UNCHANGED (same identity,
    // not coerced into EtcdError), with its description preserved.
    func TestSkillProbe_UnknownPassThrough(t *testing.T) {
    	orig := stderrors.New("totally unrecognized boom")
    	got := Error(orig)
    	if got != orig {
    		t.Fatalf("Error(unknown) returned a different error: got %#v (%v), want the same instance", got, got)
    	}
    	var ee EtcdError
    	if stderrors.As(got, &ee) {
    		t.Fatalf("Error(unknown) was coerced into EtcdError: %#v", ee)
    	}
    	if got.Error() != "totally unrecognized boom" {
    		t.Fatalf("Error(unknown) desc = %q, want %q", got.Error(), "totally unrecognized boom")
    	}
    	if ErrorDesc(got) != "totally unrecognized boom" {
    		t.Fatalf("ErrorDesc(unknown) = %q, want %q", ErrorDesc(got), "totally unrecognized boom")
    	}
    }

    // SKILLPROBE 2b: an unknown error whose message happens to be a non-table
    // string must NOT accidentally resolve to a known error. Guards against an
    // implementation that ignores the description-keyed lookup.
    func TestSkillProbe_UnknownNotInTable(t *testing.T) {
    	weird := stderrors.New("etcdserver: this exact text is not a registered error")
    	if _, registered := errStringToError[ErrorDesc(weird)]; registered {
    		t.Fatalf("test precondition broken: %q is unexpectedly in the table", weird.Error())
    	}
    	got := Error(weird)
    	if got != weird {
    		t.Fatalf("Error(non-table) = %#v, want unchanged input", got)
    	}
    }

    // SKILLPROBE 3: nil translates to nil.
    func TestSkillProbe_NilStaysNil(t *testing.T) {
    	if got := Error(nil); got != nil {
    		t.Fatalf("Error(nil) = %#v, want nil", got)
    	}
    }

    // SKILLPROBE 4: ErrorDesc returns the transport message for a transport
    // (status) error and the plain .Error() string for a non-transport error.
    func TestSkillProbe_ErrorDescSemantics(t *testing.T) {
    	transport := status.Error(codes.InvalidArgument, "carried message")
    	if d := ErrorDesc(transport); d != "carried message" {
    		t.Fatalf("ErrorDesc(transport) = %q, want %q", d, "carried message")
    	}
    	plain := stderrors.New("plain message")
    	if d := ErrorDesc(plain); d != "plain message" {
    		t.Fatalf("ErrorDesc(plain) = %q, want %q", d, "plain message")
    	}
    }

    // SKILLPROBE 5: the description is PRESERVED across conversion --
    // ErrorDesc(serverErr) == ErrorDesc(Error(serverErr)) for every known error.
    func TestSkillProbe_DescPreservedAcrossConversion(t *testing.T) {
    	known := []error{
    		ErrGRPCEmptyKey,
    		ErrGRPCKeyNotFound,
    		ErrGRPCMemberNotFound,
    		ErrGRPCNoSpace,
    		ErrGRPCCompacted,
    		ErrGRPCFutureRev,
    		ErrGRPCRequestTooManyRequests,
    	}
    	for _, se := range known {
    		conv := Error(se)
    		if ErrorDesc(se) != ErrorDesc(conv) {
    			t.Fatalf("desc not preserved for %v: server=%q converted=%q",
    				se, ErrorDesc(se), ErrorDesc(conv))
    		}
    		// And the converted code must match the source code.
    		if st, ok := status.FromError(se); ok {
    			if got := skillProbeCode(t, conv); got != st.Code() {
    				t.Fatalf("code not preserved for %v: server=%v converted=%v", se, st.Code(), got)
    			}
    		}
    	}
    }

    // SKILLPROBE 6: identification must go through the package's own
    // description-keyed table -- i.e. the table maps a description back to the
    // exact server error, and Error() honors that mapping.
    func TestSkillProbe_TableDrivenIdentification(t *testing.T) {
    	for desc, serverErr := range errStringToError {
    		// The table key really is the server error's description.
    		if ErrorDesc(serverErr) != desc {
    			t.Fatalf("table key %q != ErrorDesc(value) %q", desc, ErrorDesc(serverErr))
    		}
    		// Conversion of a fresh status error carrying the same description and
    		// code must classify to the same code as the registered server error.
    		st, ok := status.FromError(serverErr)
    		if !ok {
    			continue
    		}
    		synthetic := status.Error(st.Code(), desc)
    		conv := Error(synthetic)
    		if skillProbeCode(t, conv) != st.Code() {
    			t.Fatalf("table-driven conv for %q: code = %v, want %v",
    				desc, skillProbeCode(t, conv), st.Code())
    		}
    		if ErrorDesc(conv) != desc {
    			t.Fatalf("table-driven conv for %q: desc = %q, want %q",
    				desc, ErrorDesc(conv), desc)
    		}
    	}
    }
    '''
)


@pytest.fixture(scope="module", autouse=True)
def _install_probe_and_cleanup():
    """Install the independent probe test into the package, remove afterwards."""
    assert os.path.isdir(PKG_DIR), f"package dir missing: {PKG_DIR}"
    with open(PROBE_PATH, "w") as fh:
        fh.write(PROBE_SOURCE)
    try:
        yield
    finally:
        try:
            os.remove(PROBE_PATH)
        except OSError:
            pass


class TestGrpcServiceDefinition:
    REPO_DIR = _find_repo_dir("/workspace/etcd")

    # ---------------------- L1: deliverables exist / well-formed -------------

    def test_error_go_exists(self):
        """L1: the conversion source file `error.go` exists."""
        assert os.path.isfile(ERROR_GO), f"missing {ERROR_GO}"

    def test_error_test_go_exists(self):
        """L1: the test file `error_test.go` exists."""
        assert os.path.isfile(ERROR_TEST_GO), f"missing {ERROR_TEST_GO}"

    def test_error_go_defines_conversion_api(self):
        """L1: `error.go` still defines Error, ErrorDesc, EtcdError + the table."""
        with open(ERROR_GO) as fh:
            src = fh.read()
        assert "func Error(" in src, "Error function definition not found"
        assert "func ErrorDesc(" in src, "ErrorDesc function definition not found"
        assert "type EtcdError struct" in src, "EtcdError type not found"
        assert "errStringToError" in src, "errStringToError table not found"

    def test_error_test_defines_error_conversion_test(self):
        """L1: the deliverable test `TestErrorConversion` was added."""
        with open(ERROR_TEST_GO) as fh:
            src = fh.read()
        assert "func TestErrorConversion(" in src, (
            "TestErrorConversion not found in error_test.go (the required new "
            "test was not added)"
        )

    def test_error_test_keeps_testconvert(self):
        """L1: the pre-existing `TestConvert` was not deleted."""
        with open(ERROR_TEST_GO) as fh:
            src = fh.read()
        assert "func TestConvert(" in src, "TestConvert was removed from error_test.go"

    # ---------------------- L2: native build + behavior ----------------------

