"""
Test for 'go-testify-patterns' skill (variant ext7) — Experiment-Keyword List
Classifier in the `internal/experiments` package of hashicorp/terraform.

Variant task: the agent must add a self-contained helper
`internal/experiments/classify_list.go` (package `experiments`) exposing:

    type KeywordClassification struct {
        Current   []string
        Concluded []string
        Unknown   []string
    }
    func ClassifyKeywords(raw []string) KeywordClassification

plus a testify-based test file `internal/experiments/classify_list_test.go`
whose launcher is `TestClassifyKeywords`. `ClassifyKeywords` classifies each
trimmed, non-empty keyword via the package's own `GetCurrent` lookup and its
`ConcludedError` / `UnavailableError` error types. Buckets are sorted ascending,
de-duplicated, never nil, and the function is deterministic / order-independent.

Verification strategy (discriminative power):
Rather than trusting the agent's own test, the L2 cases write an INDEPENDENT Go
test file (`zz_bench_classify_test.go`) directly into the `experiments` package.
Because the production registry currently has NO active "current" experiments
(every registered experiment is concluded), the driver uses the package's own
`OverrideForTesting` hook to install a deterministic registry of one current +
one concluded experiment, then deep-validates real classification behavior:
correct bucketing of current/concluded/unknown keywords, whitespace trimming,
empty-entry dropping, de-duplication, ascending sort, non-nil empty slices, and
order-independence under shuffling. Each sub-test prints a unique marker that the
python layer asserts on. A naive implementation (hardcoded buckets, no trimming,
no dedup/sort, nil slices, ignoring GetCurrent) cannot pass. The driver file is
removed in teardown. Finally the agent's own mandated testify command is run.
"""

