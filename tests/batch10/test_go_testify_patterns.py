"""
Test for 'go-testify-patterns' skill (variant ext10) — Bracket-Balance Checker
for the REPL package (hashicorp/terraform).

Variant task summary:
  The agent adds a self-contained, network-free helper to the existing
  `internal/repl` package:
    - `internal/repl/brackets.go` (new) exposing
        type BracketBalance struct { Open int; Balanced bool }
        func CheckBracketBalance(src string) BracketBalance
    - `internal/repl/brackets_test.go` (new) — a deterministic test using
      github.com/stretchr/testify exercising CheckBracketBalance.

  CheckBracketBalance scans `src` once tracking the three bracket pairs
  (), [], {}. Proper nesting is required. A closer with no matching opener
  keeps `Open` >= 0 and marks the input unbalanced. Brackets inside
  double-quoted string literals are ignored (with `\\"` not ending the string).
  `Balanced` is true iff no mismatched/unmatched closer was seen AND Open == 0.

Verification strategy (discriminative power):
  Rather than trusting the agent's own test file, the L2 cases write an
  INDEPENDENT Go test file (`zz_bench_brackets_test.go`) into the `repl`
  package that calls `CheckBracketBalance` directly and deep-validates the
  exact `Open`/`Balanced` values for balanced/unclosed/stray/improperly-nested/
  string-literal/empty inputs, plus determinism. That driver uses only the
  stdlib `testing` package (no testify) so it is independent of the agent's
  harness, and it is removed in teardown. A naive implementation (e.g. one that
  ignores string literals, returns a constant, lets Open go negative, or
  doesn't enforce proper nesting) cannot pass. A final L2 case drives the
  doc's mandated native acceptance command on the agent's own testify suite.
"""

