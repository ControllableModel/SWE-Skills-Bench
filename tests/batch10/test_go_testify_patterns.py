def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/terraform")
REPL_REL = os.path.join("internal", "repl")
REPL_DIR = os.path.join(REPO_DIR, REPL_REL)

BRACKETS_SRC = os.path.join(REPL_DIR, "brackets.go")
BRACKETS_TEST = os.path.join(REPL_DIR, "brackets_test.go")

# Name chosen so it sorts last and is obviously a benchmark artifact.
DRIVER_BASENAME = "zz_bench_brackets_test.go"
DRIVER_PATH = os.path.join(REPL_DIR, DRIVER_BASENAME)


def _go_bin():
    """Locate the go binary (PYTHONPATH is cleared; PATH may be minimal)."""
    found = shutil.which("go")
    if found:
        return found
    for cand in (
        "/usr/local/go/bin/go",
        "/usr/lib/go/bin/go",
        os.path.expanduser("~/go-sdk/go/bin/go"),
        "/root/go-sdk/go/bin/go",
    ):
        if os.path.isfile(cand):
            return cand
    return "go"


GO = _go_bin()


def _run_go(args, timeout=420, cwd=REPL_DIR):
    env = dict(os.environ)
    gobin_dir = os.path.dirname(GO)
    env["PATH"] = gobin_dir + os.pathsep + env.get("PATH", "")
    env.setdefault("GOFLAGS", "-mod=mod")
    env.setdefault("GOCACHE", "/tmp/go-cache-benchmark")
    env.setdefault("CGO_ENABLED", "0")
    return subprocess.run(
        [GO] + args,
        cwd=cwd,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=env,
    )


# ---------------------------------------------------------------------------
# The independent driver test that exercises CheckBracketBalance directly.
# Each sub-test prints a unique OK marker the python layer asserts on.
# Uses ONLY the stdlib testing package so it does not depend on the agent's
# harness or on testify being wired correctly.
# ---------------------------------------------------------------------------
DRIVER_SOURCE = r'''// Code generated by the benchmark harness. DO NOT EDIT. Removed after the run.
package repl

import (
	"fmt"
	"testing"
)

func benchExpect(t *testing.T, src string, wantOpen int, wantBalanced bool) {
	t.Helper()
	got := CheckBracketBalance(src)
	if got.Open != wantOpen {
		t.Fatalf("CheckBracketBalance(%q).Open = %d, want %d (full=%+v)", src, got.Open, wantOpen, got)
	}
	if got.Balanced != wantBalanced {
		t.Fatalf("CheckBracketBalance(%q).Balanced = %v, want %v (full=%+v)", src, got.Balanced, wantBalanced, got)
	}
}

// A fully balanced nested snippet: Open == 0, Balanced == true.
func TestBenchBalancedNested(t *testing.T) {
	benchExpect(t, "foo(bar[1])", 0, true)
	benchExpect(t, "({[]})", 0, true)
	benchExpect(t, "a{b(c)d}e[f]", 0, true)
	fmt.Println("BENCH_OK_balanced_nested")
}

// Unclosed snippet: correct positive Open count, Balanced == false.
func TestBenchUnclosedOpenCount(t *testing.T) {
	benchExpect(t, "foo(bar", 1, false)
	benchExpect(t, "(((", 3, false)
	benchExpect(t, "a([{", 3, false)
	// one closed, two still open
	benchExpect(t, "([{}", 1, false)
	fmt.Println("BENCH_OK_unclosed_open_count")
}

// Stray closer with no opener: Open stays 0 (never negative), Balanced false.
func TestBenchStrayCloserNonNegative(t *testing.T) {
	benchExpect(t, "a]b", 0, false)
	benchExpect(t, ")", 0, false)
	benchExpect(t, "}}}", 0, false)
	// extra closers beyond openers must not drive Open below zero
	benchExpect(t, "()))", 0, false)
	fmt.Println("BENCH_OK_stray_nonnegative")
}

// Improper nesting: ([)] must be unbalanced (mismatched closer).
func TestBenchImproperNesting(t *testing.T) {
	got := CheckBracketBalance("([)]")
	if got.Balanced {
		t.Fatalf("([)] must be unbalanced, got %+v", got)
	}
	if got.Open < 0 {
		t.Fatalf("Open must never be negative, got %d", got.Open)
	}
	// mismatched closer of the wrong kind
	g2 := CheckBracketBalance("(]")
	if g2.Balanced {
		t.Fatalf("(] must be unbalanced, got %+v", g2)
	}
	g3 := CheckBracketBalance("{[}]")
	if g3.Balanced {
		t.Fatalf("{[}] must be unbalanced, got %+v", g3)
	}
	fmt.Println("BENCH_OK_improper_nesting")
}

// Brackets inside double-quoted string literals are ignored, including an
// escaped \" that does not end the string.
func TestBenchStringLiteralIgnored(t *testing.T) {
	// brackets only inside a string -> balanced, Open 0
	benchExpect(t, "x = \"(]{\"", 0, true)
	// an escaped quote inside the string keeps us inside; trailing real
	// brackets outside the string still count.
	benchExpect(t, "\"a\\\"b)\"(", 1, false)
	// real bracket outside, ignored bracket inside string -> Open counts only the real one
	benchExpect(t, "(\")\")", 0, true)
	// closer inside string must NOT cancel a real opener
	benchExpect(t, "(\"]\"", 1, false)
	fmt.Println("BENCH_OK_string_literal")
}

// Empty string is balanced with Open == 0.
func TestBenchEmptyString(t *testing.T) {
	benchExpect(t, "", 0, true)
	// whitespace / non-bracket characters only
	benchExpect(t, "   hello world  \n", 0, true)
	fmt.Println("BENCH_OK_empty_string")
}

// Non-bracket, non-quote characters are ignored and do not affect counts.
func TestBenchNonBracketIgnored(t *testing.T) {
	benchExpect(t, "abc123!@#$%^&*-=_+/.,<>?;:", 0, true)
	benchExpect(t, "a+b*(c-d)/e", 0, true)
	fmt.Println("BENCH_OK_non_bracket")
}

// Determinism: identical inputs yield identical results.
func TestBenchDeterministic(t *testing.T) {
	inputs := []string{"foo(bar[1])", "([)]", "x = \"(]{\"", "(((", "a]b", ""}
	for _, in := range inputs {
		a := CheckBracketBalance(in)
		b := CheckBracketBalance(in)
		if a.Open != b.Open || a.Balanced != b.Balanced {
			t.Fatalf("non-deterministic result for %q: %+v vs %+v", in, a, b)
		}
	}
	fmt.Println("BENCH_OK_deterministic")
}
'''


def _write_driver():
    with open(DRIVER_PATH, "w") as f:
        f.write(DRIVER_SOURCE)


def _remove_driver():
    try:
        os.remove(DRIVER_PATH)
    except OSError:
        pass


@pytest.fixture(scope="module", autouse=True)
def _warmup_go_modules():
    """Pre-fetch module deps once so per-test native commands don't re-download."""
    if os.path.isdir(REPL_DIR):
        try:
            _run_go(["mod", "download"], timeout=600, cwd=REPO_DIR)
        except Exception:
            pass
    yield


@pytest.fixture(scope="module")
def driver_run():
    """
    Build & run the independent benchmark driver once for the module.
    Returns the CompletedProcess so individual tests can assert on markers.
    """
    assert os.path.isdir(REPL_DIR), f"repl package dir missing: {REPL_DIR}"
    assert os.path.isfile(BRACKETS_SRC), "brackets.go was not created by the agent"

    _write_driver()
    try:
        proc = _run_go(
            ["test", "-run", "TestBench", "-v", "-count=1", "-timeout=120s", "./"],
            timeout=600,
        )
    finally:
        _remove_driver()
    return proc


def _assert_marker(proc, marker):
    combined = (proc.stdout or "") + "\n" + (proc.stderr or "")
    assert proc.returncode == 0, (
        f"benchmark driver `go test` failed (rc={proc.returncode}).\n"
        f"STDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )
    assert marker in combined, (
        f"expected marker {marker!r} not found in driver output.\n"
        f"STDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )


