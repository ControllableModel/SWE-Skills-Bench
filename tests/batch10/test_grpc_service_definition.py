"""Tests for the `grpc-service-definition` skill (variant ext10).

Skill / task: Gate which RPCs a learner member may serve in etcd's v3 RPC
layer. The predicate `isRPCSupportedForLearner` (in
`server/etcdserver/api/v3rpc/util.go`) is the single source of truth for the
learner policy. It takes a request value (`any`) and returns whether a
non-voting learner member may serve it:

  * a `*pb.StatusRequest` MUST be allowed;
  * a `*pb.RangeRequest` MUST be allowed ONLY when `Serializable == true`
    (a linearizable read needs the leader, so a non-serializable range MUST
    be disallowed);
  * every other request type -- put, delete-range, txn, compaction, and any
    unrecognized / unrelated value -- MUST be disallowed;
  * an unrelated value (e.g. a plain string, nil) MUST be disallowed WITHOUT
    panicking;
  * the decision MUST be based on the request's concrete type (and, for a
    range, on the serializable flag) -- never on a string representation.

Verification strategy
---------------------
L1 checks the deliverable files exist and are minimally well-formed
(`util.go` still defines `isRPCSupportedForLearner`; `util_test.go` still
holds the canonical `TestGRPCError`).

L2 drives the repo's native Go toolchain. The discriminative L2 cases do NOT
trust the test file the agent may have written: this module installs an
*independent* probe test (`zz_skillprobe_learner_test.go`) into the `v3rpc`
package that calls the unexported `isRPCSupportedForLearner` directly and
deep-validates the boolean result for every requirement -- the serializable
vs. linearizable range distinction, the disallow-by-default behavior, and the
no-panic robustness for an unrelated value. A naive implementation (always
returns true/false, ignores the serializable flag, allows mutations, or
decides on a stringified request) fails these probes.
"""

import os
import subprocess
import textwrap

import pytest

def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/etcd")
PKG_REL = "etcdserver/api/v3rpc"
SERVER_DIR = os.path.join(REPO_DIR, "server")
PKG_DIR = os.path.join(SERVER_DIR, PKG_REL)
UTIL_GO = os.path.join(PKG_DIR, "util.go")
UTIL_TEST_GO = os.path.join(PKG_DIR, "util_test.go")

PROBE_BASENAME = "zz_skillprobe_learner_test.go"
PROBE_PATH = os.path.join(PKG_DIR, PROBE_BASENAME)

GO_ENV = {
    **os.environ,
    "GOFLAGS": os.environ.get("GOFLAGS", ""),
    "CGO_ENABLED": "0",
}


def _go(args, timeout=600):
    """Run a `go` command from the server module dir."""
    return subprocess.run(
        ["go"] + args,
        cwd=SERVER_DIR,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=GO_ENV,
    )


# --------------------------------------------------------------------------
# Independent probe test installed into the package.
#
# It lives in `package v3rpc` so it can call the unexported
# `isRPCSupportedForLearner`. Each requirement is a hard assertion; the whole
# file must compile AND pass.
# --------------------------------------------------------------------------
PROBE_SOURCE = textwrap.dedent(
    '''\
    // Code generated by the skill benchmark. DO NOT keep.
    package v3rpc

    import (
    	"testing"

    	pb "go.etcd.io/etcd/api/v3/etcdserverpb"
    )

    // SKILLPROBE A: a status request must be allowed.
    func TestSkillProbeLearner_StatusAllowed(t *testing.T) {
    	if !isRPCSupportedForLearner(&pb.StatusRequest{}) {
    		t.Fatalf("*pb.StatusRequest must be allowed for a learner, got false")
    	}
    }

    // SKILLPROBE B: a serializable range read must be allowed; a
    // non-serializable (linearizable) range read must be DISALLOWED. This is
    // the core distinction: an implementation that ignores the flag and always
    // returns true for *pb.RangeRequest fails here.
    func TestSkillProbeLearner_RangeSerializableDistinction(t *testing.T) {
    	if !isRPCSupportedForLearner(&pb.RangeRequest{Serializable: true}) {
    		t.Fatalf("serializable *pb.RangeRequest must be allowed, got false")
    	}
    	if isRPCSupportedForLearner(&pb.RangeRequest{Serializable: false}) {
    		t.Fatalf("non-serializable (linearizable) *pb.RangeRequest must be disallowed, got true")
    	}
    	// Explicit zero-value range (Serializable defaults to false) is linearizable.
    	if isRPCSupportedForLearner(&pb.RangeRequest{}) {
    		t.Fatalf("zero-value *pb.RangeRequest is linearizable and must be disallowed, got true")
    	}
    }

    // SKILLPROBE C: every mutating / non-read request type must be disallowed.
    func TestSkillProbeLearner_MutationsDisallowed(t *testing.T) {
    	cases := []struct {
    		name string
    		req  any
    	}{
    		{"PutRequest", &pb.PutRequest{}},
    		{"DeleteRangeRequest", &pb.DeleteRangeRequest{}},
    		{"TxnRequest", &pb.TxnRequest{}},
    		{"CompactionRequest", &pb.CompactionRequest{}},
    		{"LeaseGrantRequest", &pb.LeaseGrantRequest{}},
    		{"AuthEnableRequest", &pb.AuthEnableRequest{}},
    		{"MemberAddRequest", &pb.MemberAddRequest{}},
    	}
    	for _, c := range cases {
    		if isRPCSupportedForLearner(c.req) {
    			t.Fatalf("%s must be disallowed for a learner, got true", c.name)
    		}
    	}
    }

    // SKILLPROBE D: an unrelated value whose concrete type is none of the
    // recognized request types must be disallowed -- and must NOT panic.
    func TestSkillProbeLearner_UnrelatedDisallowedNoPanic(t *testing.T) {
    	defer func() {
    		if r := recover(); r != nil {
    			t.Fatalf("isRPCSupportedForLearner panicked on unrelated value: %v", r)
    		}
    	}()
    	if isRPCSupportedForLearner("not a request") {
    		t.Fatalf("a plain string must be disallowed, got true")
    	}
    	if isRPCSupportedForLearner(42) {
    		t.Fatalf("an int must be disallowed, got true")
    	}
    	if isRPCSupportedForLearner(struct{ X int }{X: 1}) {
    		t.Fatalf("an arbitrary struct must be disallowed, got true")
    	}
    	if isRPCSupportedForLearner(nil) {
    		t.Fatalf("a nil request must be disallowed, got true")
    	}
    }

    // SKILLPROBE E: the decision must be by concrete TYPE, not by a string
    // representation. A *pb.PutRequest carrying a key/value whose bytes spell
    // out "status" or "range" must still be disallowed (a naive string-matching
    // implementation would be fooled here).
    func TestSkillProbeLearner_NotStringBased(t *testing.T) {
    	put := &pb.PutRequest{Key: []byte("statusRangeSerializable"), Value: []byte("serializable status range")}
    	if isRPCSupportedForLearner(put) {
    		t.Fatalf("a PutRequest with status/range-like bytes must still be disallowed, got true")
    	}
    	// A serializable range whose fields look unrelated must STILL be allowed
    	// purely because of its concrete type + Serializable flag.
    	rng := &pb.RangeRequest{Key: []byte("zzz"), Serializable: true}
    	if !isRPCSupportedForLearner(rng) {
    		t.Fatalf("a serializable RangeRequest must be allowed regardless of key bytes, got false")
    	}
    }

    // SKILLPROBE F: full policy matrix asserted in one table -- guards against
    // an implementation that special-cases a single probe.
    func TestSkillProbeLearner_PolicyMatrix(t *testing.T) {
    	cases := []struct {
    		name string
    		req  any
    		want bool
    	}{
    		{"status", &pb.StatusRequest{}, true},
    		{"range/serializable", &pb.RangeRequest{Serializable: true}, true},
    		{"range/linearizable", &pb.RangeRequest{Serializable: false}, false},
    		{"put", &pb.PutRequest{}, false},
    		{"delete", &pb.DeleteRangeRequest{}, false},
    		{"txn", &pb.TxnRequest{}, false},
    		{"compaction", &pb.CompactionRequest{}, false},
    		{"string", "x", false},
    		{"nil", nil, false},
    	}
    	for _, c := range cases {
    		got := isRPCSupportedForLearner(c.req)
    		if got != c.want {
    			t.Fatalf("policy[%s] = %v, want %v", c.name, got, c.want)
    		}
    	}
    }
    '''
)


@pytest.fixture(scope="module", autouse=True)
def _install_probe_and_cleanup():
    """Install the independent probe test into the package, remove afterwards."""
    assert os.path.isdir(PKG_DIR), f"package dir missing: {PKG_DIR}"
    with open(PROBE_PATH, "w") as fh:
        fh.write(PROBE_SOURCE)
    try:
        yield
    finally:
        try:
            os.remove(PROBE_PATH)
        except OSError:
            pass


class TestGrpcServiceDefinition:
    REPO_DIR = _find_repo_dir("/workspace/etcd")

