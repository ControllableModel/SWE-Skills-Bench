def _write_driver():
    with open(DRIVER_PATH, "w") as f:
        f.write(DRIVER_SOURCE)


def _remove_driver():
    try:
        os.remove(DRIVER_PATH)
    except OSError:
        pass


@pytest.fixture(scope="module", autouse=True)
def _warmup_go_modules():
    """Pre-fetch module deps once so per-test native commands don't re-download."""
    if os.path.isdir(TFDIAGS_DIR):
        try:
            _run_go(["mod", "download"], timeout=600)
        except Exception:
            pass
    yield


@pytest.fixture(scope="module")
def driver_run():
    """
    Build & run the independent benchmark driver once for the module.
    Returns the CompletedProcess so individual tests can assert on markers.
    """
    assert os.path.isdir(TFDIAGS_DIR), f"tfdiags package dir missing: {TFDIAGS_DIR}"
    summary = os.path.join(TFDIAGS_DIR, "summary.go")
    assert os.path.isfile(summary), "summary.go was not created by the agent"

    _write_driver()
    try:
        proc = _run_go(
            ["test", "-run", "TestBench", "-v", "-count=1", "-timeout=120s", "./"],
            timeout=600,
        )
    finally:
        _remove_driver()
    return proc


def _assert_marker(proc, marker):
    combined = (proc.stdout or "") + "\n" + (proc.stderr or "")
    assert proc.returncode == 0, (
        f"benchmark driver `go test` failed (rc={proc.returncode}).\n"
        f"STDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )
    assert marker in combined, (
        f"expected marker {marker!r} not found in driver output.\n"
        f"STDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )


class TestGoTestifyPatterns:
    """Verify the deterministic severity-summary helper and its testify suite."""

    REPO_DIR = _find_repo_dir("/workspace/terraform")

    # ------------------------------------------------------------------
    # L1: deliverable files exist and are minimally well-formed
    # ------------------------------------------------------------------
    def test_summary_source_exists(self):
        """summary.go must exist in the tfdiags package and declare package tfdiags."""
        p = os.path.join(TFDIAGS_DIR, "summary.go")
        assert os.path.isfile(p), f"missing deliverable {p}"
        with open(p) as f:
            content = f.read()
        assert "package tfdiags" in content, "summary.go must be in package tfdiags"
        # Spec-mandated surface must be declared (not merely a related-looking file).
        assert "SummarizeSeverities" in content, "summary.go must define SummarizeSeverities"
        assert "SeveritySummary" in content, "summary.go must define SeveritySummary"

    def test_summary_test_exists(self):
        """summary_test.go (agent's testify suite) must exist in package tfdiags."""
        p = os.path.join(TFDIAGS_DIR, "summary_test.go")
        assert os.path.isfile(p), f"missing deliverable {p}"
        with open(p) as f:
            content = f.read()
        assert "package tfdiags" in content, "summary_test.go must be in package tfdiags"
        # Mandated launcher and testify usage.
        assert "TestSummarizeSeverities" in content, (
            "summary_test.go must define the mandated TestSummarizeSeverities launcher"
        )
        assert "stretchr/testify" in content, (
            "the test must use github.com/stretchr/testify per the acceptance criteria"
        )

    def test_package_compiles(self):
        """The tfdiags package must still build with the new file added."""
        proc = _run_go(["build", "./"], timeout=600)
        assert proc.returncode == 0, (
            f"`go build ./` failed:\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
        )

    # ------------------------------------------------------------------
    # L2: independent dynamic execution of the new API (driver test)
    # ------------------------------------------------------------------
    def test_mixed_counts(self, driver_run):
        """two errors + one warning -> {Errors:2, Warnings:1, Other:0}, HasErrors()==true."""
        _assert_marker(driver_run, "BENCH_OK_mixed")

    def test_errors_only(self, driver_run):
        """errors-only collection: HasErrors() true, Warnings==0, Other==0."""
        _assert_marker(driver_run, "BENCH_OK_errors_only")

    def test_warnings_only(self, driver_run):
        """warnings-only collection: HasErrors() false, Errors==0."""
        _assert_marker(driver_run, "BENCH_OK_warnings_only")

    def test_empty_and_nil(self, driver_run):
        """nil and empty Diagnostics yield an all-zero summary without panicking."""
        _assert_marker(driver_run, "BENCH_OK_empty_nil")

    def test_invariant_holds(self, driver_run):
        """Errors+Warnings+Other == len(diags) across several collections."""
        _assert_marker(driver_run, "BENCH_OK_invariant")

    def test_haserrors_boundary(self, driver_run):
        """HasErrors() is driven solely by Errors>0, independent of Warnings/Other."""
        _assert_marker(driver_run, "BENCH_OK_haserrors_boundary")

    def test_no_mutation(self, driver_run):
        """SummarizeSeverities must not mutate the receiver (length/severities unchanged)."""
        _assert_marker(driver_run, "BENCH_OK_no_mutation")

    def test_deterministic(self, driver_run):
        """identical inputs and repeated calls produce identical summaries."""
        _assert_marker(driver_run, "BENCH_OK_deterministic")

    def test_scaled_counts(self, driver_run):
        """7 errors + 5 warnings -> exact 7/5/0 counts and total 12."""
        _assert_marker(driver_run, "BENCH_OK_scaled")

    # ------------------------------------------------------------------
    # L2: the agent's own testify suite must pass under the mandated command
    # ------------------------------------------------------------------
    def test_agent_testify_suite_passes(self):
        """`go test ./internal/tfdiags/ -run TestSummarizeSeverities -v` (mandated) must pass."""
        proc = _run_go(
            ["test", "-run", "TestSummarizeSeverities", "-v", "-count=1", "-timeout=120s", "./"],
            timeout=600,
        )
        out = (proc.stdout or "") + "\n" + (proc.stderr or "")
        assert proc.returncode == 0, (
            f"mandated testify command failed:\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
        )
        assert "TestSummarizeSeverities" in out, (
            "TestSummarizeSeverities did not run; output:\n" + out
        )
        assert "no tests to run" not in out, (
            "TestSummarizeSeverities matched nothing:\n" + out
        )
        assert "ok" in out or "PASS" in out, "mandated suite did not pass:\n" + out
