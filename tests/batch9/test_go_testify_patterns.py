"""
Test for 'go-testify-patterns' skill (variant ext9) — Severity-Summary Helper
for the diagnostics package (hashicorp/terraform).

Variant task: the agent adds a deterministic, network-free summary helper to the
existing `internal/tfdiags` package:

  type SeveritySummary struct {
      Errors   int
      Warnings int
      Other    int
  }
  func (diags Diagnostics) SummarizeSeverities() SeveritySummary
  func (s SeveritySummary) HasErrors() bool

plus a deterministic testify-based test file
`internal/tfdiags/summary_test.go` whose launcher is `TestSummarizeSeverities`.

Mandated acceptance command (from the requirement doc):
    go test ./internal/tfdiags/ -run TestSummarizeSeverities -v

Verification strategy (discriminative power):
The L2 cases do NOT trust the agent's own test file. They drop an INDEPENDENT Go
test file (`zz_bench_summary_test.go`) directly into the `tfdiags` package that
constructs Diagnostics via the package's real constructors (`Sourceless(Error,…)`,
`SimpleWarning(…)`) and calls `SummarizeSeverities` / `HasErrors` directly,
deep-validating exact counts, the `Errors+Warnings+Other == len(diags)` invariant,
nil/empty handling, receiver non-mutation, and determinism. The driver is removed
in teardown. A naive implementation (hardcoded counts, ignoring the receiver,
miscounting "Other", or mutating input) cannot pass these. A final L2 case also
runs the agent's own mandated testify command.
"""

