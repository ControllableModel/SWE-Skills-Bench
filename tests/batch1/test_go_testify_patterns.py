"""
Test for 'go-testify-patterns' skill — Deterministic Chunk-Planning Layer for
the Consul state backend (hashicorp/terraform).

Verifies that the agent added a network-free `chunkplan.go` to the
`internal/backend/remote-state/consul` package exposing:
  - func PlanStorage(basePath string, payload []byte, limit int) (StoragePlan, error)
  - func ClassifyStoredValue(value []byte) StoredKind
and a testify-suite test file `chunkplan_test.go` whose launcher is
`TestStoragePlanSuite`.

Strategy for discriminative power: rather than trusting the agent's own test
file, most L2 cases write an INDEPENDENT Go test file (`zz_bench_chunkplan_test.go`)
into the consul package that calls `PlanStorage` / `ClassifyStoredValue`
directly and deep-validates real behavior (chunk slicing, reconstruction,
MD5-consistent key paths, link-record JSON round-trip, classification, error
handling). That file is removed in teardown. A naive / file-only / hardcoded
solution cannot pass these.
"""

