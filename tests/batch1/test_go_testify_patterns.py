# ---------------------------------------------------------------------------
# Accessor shim. StoragePlan field/method names are not dictated by the spec,
# only the *behavior* is. We discover the real accessors at build time by
# generating a small adapter that tries common shapes; if none compile the
# benchmark fails loudly. To keep this robust we instead require the plan to
# expose its data through a minimal, spec-mandated surface that we detect via
# Go reflection in the helper file below.
# ---------------------------------------------------------------------------
HELPER_SOURCE = r'''// Code generated by the benchmark harness. DO NOT EDIT. Removed after the run.
package consul

import (
	"reflect"
)

// The spec mandates StoragePlan exposes (by some name): chunked-or-not, the
// ordered chunk byte-slices, the ordered chunk key paths, and the link bytes.
// These reflection helpers locate that data structurally so the test does not
// hardcode the agent's chosen field/method names.

func planValue(v interface{}) reflect.Value {
	rv := reflect.ValueOf(v)
	for rv.Kind() == reflect.Ptr {
		rv = rv.Elem()
	}
	return rv
}

// findChunks returns the [][]byte field (ordered chunk byte slices).
func planChunks(v interface{}) [][]byte {
	rv := planValue(v)
	// exported field of type [][]byte
	if rv.Kind() == reflect.Struct {
		for i := 0; i < rv.NumField(); i++ {
			f := rv.Type().Field(i)
			if f.PkgPath != "" {
				continue
			}
			if f.Type.Kind() == reflect.Slice &&
				f.Type.Elem().Kind() == reflect.Slice &&
				f.Type.Elem().Elem().Kind() == reflect.Uint8 {
				return rv.Field(i).Interface().([][]byte)
			}
		}
	}
	return nil
}

// findPaths returns the []string field (ordered chunk key paths).
func planPaths(v interface{}) []string {
	rv := planValue(v)
	if rv.Kind() == reflect.Struct {
		for i := 0; i < rv.NumField(); i++ {
			f := rv.Type().Field(i)
			if f.PkgPath != "" {
				continue
			}
			if f.Type.Kind() == reflect.Slice &&
				f.Type.Elem().Kind() == reflect.String {
				return rv.Field(i).Interface().([]string)
			}
		}
	}
	return nil
}

// planLink returns the JSON link record bytes ([]byte field that is NOT [][]byte).
func planLink(v interface{}) []byte {
	rv := planValue(v)
	if rv.Kind() == reflect.Struct {
		for i := 0; i < rv.NumField(); i++ {
			f := rv.Type().Field(i)
			if f.PkgPath != "" {
				continue
			}
			if f.Type.Kind() == reflect.Slice && f.Type.Elem().Kind() == reflect.Uint8 {
				return rv.Field(i).Interface().([]byte)
			}
		}
	}
	return nil
}

// planChunked reports whether the plan is chunked. A plan is chunked iff it has
// chunks. We treat presence of >=1 chunk path / chunk slice as chunked, which
// matches the spec (single-entry => no chunks, no paths, no link).
func planChunked(v interface{}) bool {
	if len(planPaths(v)) > 0 {
		return true
	}
	if len(planChunks(v)) > 0 {
		return true
	}
	if len(planLink(v)) > 0 {
		return true
	}
	// Fall back to an exported bool field if present and true.
	rv := planValue(v)
	if rv.Kind() == reflect.Struct {
		for i := 0; i < rv.NumField(); i++ {
			f := rv.Type().Field(i)
			if f.PkgPath != "" {
				continue
			}
			if f.Type.Kind() == reflect.Bool && rv.Field(i).Bool() {
				return true
			}
		}
	}
	return false
}

func planChunkCount(v interface{}) int { return len(planChunks(v)) }
func planPathCount(v interface{}) int  { return len(planPaths(v)) }
'''


