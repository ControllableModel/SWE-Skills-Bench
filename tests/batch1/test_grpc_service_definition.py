"""Tests for the `grpc-service-definition` skill.

Skill / task: Harden the server-side RPC error translation layer in etcd's
v3 RPC server. The single translation function `togRPCError` (in
`server/etcdserver/api/v3rpc/util.go`) must be hardened so that:

  * a known domain error wrapped with extra context resolves to the same
    over-the-wire result the bare domain error would have produced;
  * a wrapped `context.Canceled` / `context.DeadlineExceeded` is preserved
    (not flattened to the opaque "unknown" result);
  * an unmapped error that already carries a specific, non-generic transport
    (gRPC status) classification is returned unchanged with that
    classification intact;
  * an unmapped plain Go error (or one carrying only the generic/unknown
    classification) still becomes the opaque `codes.Unknown` result;
  * `nil` translates to `nil`;
  * all existing `TestGRPCError` expectations keep passing.

Verification strategy
---------------------
L1 checks the deliverable files exist and are minimally well-formed.

L2 drives the repo's native Go toolchain. Crucially, the discriminative L2
cases do NOT trust test files the agent itself may have written: this module
copies an *independent* probe test (`zz_skillprobe_test.go`) into the
`v3rpc` package, which calls the unexported `togRPCError` directly and
deep-validates the resulting gRPC status code / error identity for every
requirement. A naive solution that merely edits the existing test, or that
keeps the old flatten-everything behavior, fails these probes.
"""

import os
import subprocess
import textwrap

import pytest

def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/etcd")
PKG_REL = "etcdserver/api/v3rpc"
SERVER_DIR = os.path.join(REPO_DIR, "server")
PKG_DIR = os.path.join(SERVER_DIR, PKG_REL)
UTIL_GO = os.path.join(PKG_DIR, "util.go")
UTIL_TEST_GO = os.path.join(PKG_DIR, "util_test.go")

PROBE_BASENAME = "zz_skillprobe_test.go"
PROBE_PATH = os.path.join(PKG_DIR, PROBE_BASENAME)

GO_ENV = {
    **os.environ,
    "GOFLAGS": os.environ.get("GOFLAGS", ""),
    "CGO_ENABLED": "0",
}


def _go(args, timeout=600):
    """Run a `go` command from the server module dir."""
    return subprocess.run(
        ["go"] + args,
        cwd=SERVER_DIR,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=GO_ENV,
    )


# --------------------------------------------------------------------------
# Independent probe test installed into the package.
#
# It lives in `package v3rpc` so it can call the unexported `togRPCError`.
# Each requirement is a hard assertion; the whole thing must compile AND pass.
# --------------------------------------------------------------------------
PROBE_SOURCE = textwrap.dedent(
    '''\
    // Code generated by the skill benchmark. DO NOT keep.
    package v3rpc

    import (
    	"context"
    	stderrors "errors"
    	"fmt"
    	"testing"

    	"google.golang.org/grpc/codes"
    	"google.golang.org/grpc/status"

    	"go.etcd.io/etcd/api/v3/v3rpc/rpctypes"
    	"go.etcd.io/etcd/server/v3/storage/mvcc"
    )

    func skillProbeCodeOf(err error) codes.Code {
    	if err == nil {
    		return codes.OK
    	}
    	st, ok := status.FromError(err)
    	if !ok {
    		return codes.Unknown
    	}
    	return st.Code()
    }

    // SKILLPROBE 1: a known domain error wrapped with surrounding context must
    // resolve to the SAME over-the-wire result as the bare domain error.
    func TestSkillProbe_WrappedDomainError(t *testing.T) {
    	bare := togRPCError(mvcc.ErrCompacted)
    	if !stderrors.Is(bare, rpctypes.ErrGRPCCompacted) {
    		t.Fatalf("baseline: bare ErrCompacted -> %v, want ErrGRPCCompacted", bare)
    	}
    	if skillProbeCodeOf(bare) != codes.OutOfRange {
    		t.Fatalf("baseline: bare ErrCompacted code = %v, want OutOfRange", skillProbeCodeOf(bare))
    	}

    	wrapped := fmt.Errorf("apply failed: %w", mvcc.ErrCompacted)
    	got := togRPCError(wrapped)
    	if skillProbeCodeOf(got) != codes.OutOfRange {
    		t.Fatalf("wrapped ErrCompacted code = %v, want OutOfRange (got %v)", skillProbeCodeOf(got), got)
    	}
    	if !stderrors.Is(got, rpctypes.ErrGRPCCompacted) && got.Error() != rpctypes.ErrGRPCCompacted.Error() {
    		t.Fatalf("wrapped ErrCompacted -> %v, want same result as bare ErrGRPCCompacted", got)
    	}
    	if skillProbeCodeOf(got) == codes.Unknown {
    		t.Fatalf("wrapped domain error was flattened to Unknown: %v", got)
    	}
    }

    // SKILLPROBE 1b: deeply nested / joined chains must still resolve.
    func TestSkillProbe_DeeplyWrappedDomainError(t *testing.T) {
    	chain := fmt.Errorf("outer: %w", fmt.Errorf("inner: %w", mvcc.ErrFutureRev))
    	got := togRPCError(chain)
    	if skillProbeCodeOf(got) != codes.OutOfRange {
    		t.Fatalf("nested ErrFutureRev code = %v, want OutOfRange (got %v)", skillProbeCodeOf(got), got)
    	}
    	if got.Error() != rpctypes.ErrGRPCFutureRev.Error() && !stderrors.Is(got, rpctypes.ErrGRPCFutureRev) {
    		t.Fatalf("nested ErrFutureRev -> %v, want ErrGRPCFutureRev", got)
    	}

    	joined := stderrors.Join(stderrors.New("side"), mvcc.ErrCompacted)
    	gotJoined := togRPCError(joined)
    	if skillProbeCodeOf(gotJoined) != codes.OutOfRange {
    		t.Fatalf("joined ErrCompacted code = %v, want OutOfRange (got %v)", skillProbeCodeOf(gotJoined), gotJoined)
    	}
    }

    // SKILLPROBE 2: a wrapped context error must be PRESERVED, not flattened.
    func TestSkillProbe_WrappedContextError(t *testing.T) {
    	wc := fmt.Errorf("request aborted: %w", context.Canceled)
    	gotC := togRPCError(wc)
    	if !stderrors.Is(gotC, context.Canceled) {
    		t.Fatalf("wrapped context.Canceled -> %v, want errors.Is(context.Canceled)", gotC)
    	}
    	if skillProbeCodeOf(gotC) == codes.Unknown {
    		t.Fatalf("wrapped context.Canceled flattened to Unknown: %v", gotC)
    	}

    	wd := fmt.Errorf("deadline hit: %w", context.DeadlineExceeded)
    	gotD := togRPCError(wd)
    	if !stderrors.Is(gotD, context.DeadlineExceeded) {
    		t.Fatalf("wrapped context.DeadlineExceeded -> %v, want errors.Is(context.DeadlineExceeded)", gotD)
    	}
    }

    // SKILLPROBE 3: an unmapped error already carrying a specific, non-generic
    // transport classification must be returned UNCHANGED with that code intact.
    func TestSkillProbe_PreserveExistingStatus(t *testing.T) {
    	for _, c := range []codes.Code{codes.PermissionDenied, codes.NotFound, codes.InvalidArgument, codes.ResourceExhausted} {
    		in := status.Error(c, "preclassified: "+c.String())
    		got := togRPCError(in)
    		if skillProbeCodeOf(got) != c {
    			t.Fatalf("preclassified %v -> code %v, want preserved %v (got %v)", c, skillProbeCodeOf(got), c, got)
    		}
    		if got.Error() != in.Error() {
    			t.Fatalf("preclassified %v message changed: got %q want %q", c, got.Error(), in.Error())
    		}
    	}
    }

    // SKILLPROBE 4: an unmapped plain Go error becomes the opaque Unknown result.
    func TestSkillProbe_PlainErrorBecomesUnknown(t *testing.T) {
    	plain := stderrors.New("totally unrecognized boom")
    	got := togRPCError(plain)
    	if skillProbeCodeOf(got) != codes.Unknown {
    		t.Fatalf("plain error code = %v, want Unknown (got %v)", skillProbeCodeOf(got), got)
    	}
    	st, ok := status.FromError(got)
    	if !ok {
    		t.Fatalf("plain error -> non-status %v; want a gRPC status error", got)
    	}
    	if st.Message() != "totally unrecognized boom" {
    		t.Fatalf("plain error message = %q, want %q", st.Message(), "totally unrecognized boom")
    	}
    }

    // SKILLPROBE 4b: an error whose ONLY classification is the generic Unknown one
    // must still be turned into the opaque Unknown result (i.e. it must not be
    // mistaken for a "specific" classification to preserve).
    func TestSkillProbe_GenericUnknownStaysUnknown(t *testing.T) {
    	in := status.Error(codes.Unknown, "generic")
    	got := togRPCError(in)
    	if skillProbeCodeOf(got) != codes.Unknown {
    		t.Fatalf("generic-Unknown status -> code %v, want Unknown (got %v)", skillProbeCodeOf(got), got)
    	}
    }

    // SKILLPROBE 5: nil must translate to nil (no panic).
    func TestSkillProbe_NilStaysNil(t *testing.T) {
    	if got := togRPCError(nil); got != nil {
    		t.Fatalf("togRPCError(nil) = %v, want nil", got)
    	}
    }

    // SKILLPROBE 6: regression -- bare recognized domain error keeps its mapping.
    func TestSkillProbe_BareDomainUnchanged(t *testing.T) {
    	got := togRPCError(mvcc.ErrCompacted)
    	if got.Error() != rpctypes.ErrGRPCCompacted.Error() && !stderrors.Is(got, rpctypes.ErrGRPCCompacted) {
    		t.Fatalf("bare ErrCompacted -> %v, want ErrGRPCCompacted", got)
    	}
    }
    '''
)


@pytest.fixture(scope="module", autouse=True)
def _install_probe_and_cleanup():
    """Install the independent probe test into the package, remove afterwards."""
    assert os.path.isdir(PKG_DIR), f"package dir missing: {PKG_DIR}"
    with open(PROBE_PATH, "w") as fh:
        fh.write(PROBE_SOURCE)
    try:
        yield
    finally:
        try:
            os.remove(PROBE_PATH)
        except OSError:
            pass


class TestGrpcServiceDefinition:
    REPO_DIR = _find_repo_dir("/workspace/etcd")

    # ---------------------- L1: deliverables exist / well-formed -------------

    def test_util_go_exists(self):
        """L1: the translation source file `util.go` exists."""
        assert os.path.isfile(UTIL_GO), f"missing {UTIL_GO}"

    def test_util_test_go_exists(self):
        """L1: the test file `util_test.go` exists."""
        assert os.path.isfile(UTIL_TEST_GO), f"missing {UTIL_TEST_GO}"

    def test_util_go_defines_togrpcerror(self):
        """L1: `util.go` still defines `togRPCError` and the mapping table."""
        with open(UTIL_GO) as fh:
            src = fh.read()
        assert "func togRPCError(" in src, "togRPCError function definition not found"
        assert "toGRPCErrorMap" in src, "toGRPCErrorMap table not found"

    def test_util_test_defines_grpcerror_test(self):
        """L1: `util_test.go` still contains the canonical TestGRPCError."""
        with open(UTIL_TEST_GO) as fh:
            src = fh.read()
        assert "func TestGRPCError(" in src, "TestGRPCError not found in util_test.go"

    # ---------------------- L2: native build + behavior ----------------------

    def test_package_builds(self):
        """L2: the v3rpc package compiles (agent did not break the build)."""
        res = _go(["build", "./" + PKG_REL + "/..."])
        assert res.returncode == 0, (
            "go build failed:\n" + res.stdout + "\n" + res.stderr
        )

    def test_vet_package(self):
        """L2: `go vet` passes on the package when it is able to run."""
        res = _go(["vet", "./" + PKG_REL + "/"])
        if res.returncode != 0:
            combined = (res.stdout + res.stderr).lower()
            if (
                "cannot find" not in combined
                and "timeout" not in combined
                and "dial tcp" not in combined
                and "no such host" not in combined
            ):
                assert res.returncode == 0, (
                    "go vet reported problems:\n" + res.stdout + "\n" + res.stderr
                )

    def test_existing_grpcerror_passes(self):
        """L2: the unchanged, canonical TestGRPCError must still pass."""
        res = _go(
            ["test", "./" + PKG_REL + "/", "-run", "^TestGRPCError$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, "TestGRPCError failed:\n" + out
        assert "PASS" in out, "no PASS marker in TestGRPCError output:\n" + out
        assert "--- FAIL" not in out, "a subtest FAILED:\n" + out

    def test_probe_wrapped_domain_error(self):
        """L2: wrapped known domain error resolves to the bare mapping result."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillProbe_WrappedDomainError|TestSkillProbe_DeeplyWrappedDomainError)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "wrapped-domain-error probe failed (translation does not unwrap the "
            "error chain):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_wrapped_context_error(self):
        """L2: wrapped context errors are preserved, not flattened to Unknown."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillProbe_WrappedContextError$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "wrapped-context-error probe failed (wrapped context.Canceled / "
            "DeadlineExceeded not preserved):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_preserve_existing_classification(self):
        """L2: an unmapped error with a specific status code is returned unchanged."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillProbe_PreserveExistingStatus$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "preserve-classification probe failed (a pre-classified transport "
            "error was collapsed to Unknown):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_plain_and_generic_become_unknown(self):
        """L2: plain Go errors and generic-Unknown errors still become opaque Unknown."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillProbe_PlainErrorBecomesUnknown|TestSkillProbe_GenericUnknownStaysUnknown)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "plain/generic-unknown probe failed (opaque-unknown fallback "
            "regressed):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_nil_stays_nil(self):
        """L2: a nil error translates to nil without panicking."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillProbe_NilStaysNil$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "nil probe failed (togRPCError(nil) did not return nil / panicked):\n" + out
        )
        assert "panic" not in out.lower(), "togRPCError(nil) panicked:\n" + out
        assert "--- FAIL" not in out, out

    def test_probe_bare_domain_regression(self):
        """L2: bare recognized domain errors keep their existing mapping."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillProbe_BareDomainUnchanged$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, "bare-domain regression probe failed:\n" + out
        assert "--- FAIL" not in out, out

    def test_full_probe_suite_and_existing_pass_together(self):
        """L2: the whole behavior matrix passes in one native run (integration)."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestGRPCError|TestSkillProbe_.*)$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "combined existing + probe suite failed:\n" + out
        )
        assert "--- FAIL" not in out, "at least one case FAILED:\n" + out
        assert "ok  " in out or "PASS" in out, "no success marker:\n" + out
