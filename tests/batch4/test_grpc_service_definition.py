"""Tests for the `grpc-service-definition` skill (variant ext4).

Skill / task: Audit transaction-request size and key validation in etcd's v3
KV service. The guard `checkTxnRequest` (in
`server/etcdserver/api/v3rpc/key.go`) screens every `Txn` RPC and must:

  * cap the number of operations per transaction against the MAXIMUM of the
    three operation lists (len(Compare), len(Success), len(Failure)) -- NOT
    their sum;  a list longer than `maxTxnOps` -> ErrGRPCTooManyOps;
  * reject any comparison whose key is empty -> ErrGRPCEmptyKey;
  * keep the recursive nested-transaction budget so nested ops that push the
    effective count past `maxTxnOps` are still rejected with ErrGRPCTooManyOps;
  * return nil for an in-budget, valid, non-empty-key transaction;
  * surface rejections only as the specific `rpctypes` classifications
    (never an opaque/unknown one, never a plain Go error).

Verification strategy
---------------------
L1 checks the deliverable files exist and are minimally well-formed (the
source still defines `checkTxnRequest`, the test file adds a TestCheckTxnRequest).

L2 drives the repo's native Go toolchain. The discriminative L2 cases do NOT
trust test files the agent itself wrote: this module copies an *independent*
probe test (`zz_skillprobe_txn_test.go`) into the `v3rpc` package, which calls
the unexported `checkTxnRequest` directly and deep-validates the returned
error identity (via `errors.Is` against the exact `rpctypes` errors, and gRPC
status codes) for every requirement -- including the boundary case (largest
list == N accepted, == N+1 rejected), the "max not sum" rule, the empty
comparison key, the nested-transaction budget, and nil. A naive solution that
caps on the SUM, ignores the empty-key check, drops nested budgeting, or
returns an opaque error fails these probes.
"""

import os
import subprocess
import textwrap

import pytest

def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/etcd")
PKG_REL = "etcdserver/api/v3rpc"
SERVER_DIR = os.path.join(REPO_DIR, "server")
PKG_DIR = os.path.join(SERVER_DIR, PKG_REL)
KEY_GO = os.path.join(PKG_DIR, "key.go")
KEY_TEST_GO = os.path.join(PKG_DIR, "key_test.go")

PROBE_BASENAME = "zz_skillprobe_txn_test.go"
PROBE_PATH = os.path.join(PKG_DIR, PROBE_BASENAME)

GO_ENV = {
    **os.environ,
    "GOFLAGS": os.environ.get("GOFLAGS", ""),
    "CGO_ENABLED": "0",
}


def _go(args, timeout=600):
    """Run a `go` command from the server module dir."""
    return subprocess.run(
        ["go"] + args,
        cwd=SERVER_DIR,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=GO_ENV,
    )


# --------------------------------------------------------------------------
# Independent probe test installed into the package.
#
# It lives in `package v3rpc` so it can call the unexported `checkTxnRequest`
# and the `pb` / `rpctypes` imports the file already relies on. Each
# requirement is a hard assertion driven by list lengths and field values
# (errors.Is against the exact rpctypes errors), never string matching.
# --------------------------------------------------------------------------
PROBE_SOURCE = textwrap.dedent(
    '''\
    // Code generated by the skill benchmark. DO NOT keep.
    package v3rpc

    import (
    	stderrors "errors"
    	"testing"

    	pb "go.etcd.io/etcd/api/v3/etcdserverpb"
    	"go.etcd.io/etcd/api/v3/v3rpc/rpctypes"
    )

    // mkCompares builds n comparisons, each with a non-empty key.
    func skillMkCompares(n int) []*pb.Compare {
    	out := make([]*pb.Compare, 0, n)
    	for i := 0; i < n; i++ {
    		out = append(out, &pb.Compare{Key: []byte("k")})
    	}
    	return out
    }

    // mkPuts builds n success/failure put ops, each with a non-empty key.
    func skillMkPuts(n int) []*pb.RequestOp {
    	out := make([]*pb.RequestOp, 0, n)
    	for i := 0; i < n; i++ {
    		out = append(out, &pb.RequestOp{
    			Request: &pb.RequestOp_RequestPut{
    				RequestPut: &pb.PutRequest{Key: []byte("p"), Value: []byte("v")},
    			},
    		})
    	}
    	return out
    }

    // SKILLPROBE 1: operation-count cap is on the MAX of the three lists, at the
    // boundary. Largest list == N must be accepted (size-wise); == N+1 rejected
    // with the too-many-operations classification.
    func TestSkillProbe_OpCountCapBoundary(t *testing.T) {
    	const N = 4

    	// Success list of exactly N -> accepted.
    	ok := &pb.TxnRequest{Success: skillMkPuts(N)}
    	if err := checkTxnRequest(ok, N); err != nil {
    		t.Fatalf("N successes with maxTxnOps=N: got %v, want nil", err)
    	}

    	// Success list of N+1 -> too-many-operations.
    	tooMany := &pb.TxnRequest{Success: skillMkPuts(N + 1)}
    	err := checkTxnRequest(tooMany, N)
    	if !stderrors.Is(err, rpctypes.ErrGRPCTooManyOps) {
    		t.Fatalf("N+1 successes: got %v, want ErrGRPCTooManyOps", err)
    	}

    	// Same on the comparison list and the failure list.
    	tooManyCmp := &pb.TxnRequest{Compare: skillMkCompares(N + 1)}
    	if e := checkTxnRequest(tooManyCmp, N); !stderrors.Is(e, rpctypes.ErrGRPCTooManyOps) {
    		t.Fatalf("N+1 comparisons: got %v, want ErrGRPCTooManyOps", e)
    	}
    	tooManyFail := &pb.TxnRequest{Failure: skillMkPuts(N + 1)}
    	if e := checkTxnRequest(tooManyFail, N); !stderrors.Is(e, rpctypes.ErrGRPCTooManyOps) {
    		t.Fatalf("N+1 failures: got %v, want ErrGRPCTooManyOps", e)
    	}
    }

    // SKILLPROBE 2: the cap is the MAX across lists, not the SUM. A request with
    // N comparisons AND N successes AND N failures must be accepted size-wise.
    // A naive sum-based implementation (3N > N) would wrongly reject this.
    func TestSkillProbe_MaxNotSum(t *testing.T) {
    	const N = 4
    	r := &pb.TxnRequest{
    		Compare: skillMkCompares(N),
    		Success: skillMkPuts(N),
    		Failure: skillMkPuts(N),
    	}
    	if err := checkTxnRequest(r, N); err != nil {
    		t.Fatalf("N comparisons + N successes + N failures with maxTxnOps=N: "+
    			"got %v, want nil (cap must be max-of-lists, not sum)", err)
    	}
    }

    // SKILLPROBE 3: an empty comparison key must be rejected with the empty-key
    // classification (and not silently accepted, and not reported as too-many).
    func TestSkillProbe_EmptyComparisonKey(t *testing.T) {
    	const N = 4
    	r := &pb.TxnRequest{
    		Compare: []*pb.Compare{
    			{Key: []byte("good")},
    			{Key: []byte{}}, // empty key -> reject
    		},
    	}
    	err := checkTxnRequest(r, N)
    	if !stderrors.Is(err, rpctypes.ErrGRPCEmptyKey) {
    		t.Fatalf("empty comparison key: got %v, want ErrGRPCEmptyKey", err)
    	}
    	if stderrors.Is(err, rpctypes.ErrGRPCTooManyOps) {
    		t.Fatalf("empty comparison key misclassified as ErrGRPCTooManyOps: %v", err)
    	}
    }

    // SKILLPROBE 4: nested-transaction budget. A success entry that is itself a
    // nested txn must have its inner ops counted against the remaining budget.
    // Outer 2 successes + inner txn with 3 successes, maxTxnOps=4 -> the nested
    // ops push past the budget -> ErrGRPCTooManyOps. (Recursive budget must be
    // preserved; a flat implementation that ignores nesting would accept this.)
    func TestSkillProbe_NestedBudget(t *testing.T) {
    	const N = 4

    	nested := &pb.RequestOp{
    		Request: &pb.RequestOp_RequestTxn{
    			RequestTxn: &pb.TxnRequest{Success: skillMkPuts(3)},
    		},
    	}
    	// outer has 2 ops (1 normal put + the nested txn). Remaining budget after
    	// the outer level (max list len = 2) is N-2 = 2, but the nested txn holds
    	// 3 success ops -> exceeds the remaining budget.
    	outer := &pb.TxnRequest{
    		Success: []*pb.RequestOp{
    			skillMkPuts(1)[0],
    			nested,
    		},
    	}
    	err := checkTxnRequest(outer, N)
    	if !stderrors.Is(err, rpctypes.ErrGRPCTooManyOps) {
    		t.Fatalf("nested txn over remaining budget: got %v, want ErrGRPCTooManyOps", err)
    	}

    	// A nested txn that fits within the remaining budget must be accepted.
    	okNested := &pb.TxnRequest{
    		Success: []*pb.RequestOp{
    			{
    				Request: &pb.RequestOp_RequestTxn{
    					RequestTxn: &pb.TxnRequest{Success: skillMkPuts(2)},
    				},
    			},
    		},
    	}
    	if e := checkTxnRequest(okNested, N); e != nil {
    		t.Fatalf("in-budget nested txn (2 inner, max=4): got %v, want nil", e)
    	}
    }

    // SKILLPROBE 5: a within-budget transaction with valid, non-empty-key ops on
    // every list must return nil.
    func TestSkillProbe_ValidWithinBudget(t *testing.T) {
    	const N = 8
    	r := &pb.TxnRequest{
    		Compare: skillMkCompares(2),
    		Success: skillMkPuts(3),
    		Failure: skillMkPuts(2),
    	}
    	if err := checkTxnRequest(r, N); err != nil {
    		t.Fatalf("valid within-budget txn: got %v, want nil", err)
    	}
    }

    // SKILLPROBE 6: the documented expected-functionality table, exactly.
    func TestSkillProbe_ExpectedFunctionality(t *testing.T) {
    	// maxTxnOps=4, success list length 5 -> too-many-operations.
    	if e := checkTxnRequest(&pb.TxnRequest{Success: skillMkPuts(5)}, 4); !stderrors.Is(e, rpctypes.ErrGRPCTooManyOps) {
    		t.Fatalf("max=4, 5 successes: got %v, want ErrGRPCTooManyOps", e)
    	}
    	// each list length 4 -> accepted size-wise.
    	r := &pb.TxnRequest{
    		Compare: skillMkCompares(4),
    		Success: skillMkPuts(4),
    		Failure: skillMkPuts(4),
    	}
    	if e := checkTxnRequest(r, 4); e != nil {
    		t.Fatalf("max=4, each list 4: got %v, want nil", e)
    	}
    	// a comparison with an empty key -> empty-key error.
    	emptyKey := &pb.TxnRequest{Compare: []*pb.Compare{{Key: nil}}}
    	if e := checkTxnRequest(emptyKey, 4); !stderrors.Is(e, rpctypes.ErrGRPCEmptyKey) {
    		t.Fatalf("empty comparison key: got %v, want ErrGRPCEmptyKey", e)
    	}
    	// within-budget valid -> nil.
    	if e := checkTxnRequest(&pb.TxnRequest{Success: skillMkPuts(2)}, 4); e != nil {
    		t.Fatalf("within-budget valid: got %v, want nil", e)
    	}
    }

    // SKILLPROBE 7: empty request (all lists empty) must be accepted.
    func TestSkillProbe_EmptyRequest(t *testing.T) {
    	if e := checkTxnRequest(&pb.TxnRequest{}, 4); e != nil {
    		t.Fatalf("empty txn request: got %v, want nil", e)
    	}
    }
    '''
)


@pytest.fixture(scope="module", autouse=True)
def _install_probe_and_cleanup():
    """Install the independent probe test into the package, remove afterwards."""
    assert os.path.isdir(PKG_DIR), f"package dir missing: {PKG_DIR}"
    with open(PROBE_PATH, "w") as fh:
        fh.write(PROBE_SOURCE)
    try:
        yield
    finally:
        try:
            os.remove(PROBE_PATH)
        except OSError:
            pass


