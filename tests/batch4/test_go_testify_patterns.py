def _write_driver():
    with open(DRIVER_PATH, "w") as f:
        f.write(DRIVER_SOURCE)


def _remove_driver():
    try:
        os.remove(DRIVER_PATH)
    except OSError:
        pass


@pytest.fixture(scope="module", autouse=True)
def _warmup_go_modules():
    """Pre-fetch module deps once so per-test native commands don't re-download."""
    if os.path.isdir(IPADDR_DIR):
        try:
            _run_go(["mod", "download"], timeout=600)
        except Exception:
            pass
    yield


@pytest.fixture(scope="module")
def driver_run():
    """
    Build & run the independent benchmark driver once for the module.
    Returns the CompletedProcess so individual tests can assert on markers.
    """
    assert os.path.isdir(IPADDR_DIR), f"ipaddr package dir missing: {IPADDR_DIR}"
    cidrmatch = os.path.join(IPADDR_DIR, "cidrmatch.go")
    assert os.path.isfile(cidrmatch), "cidrmatch.go was not created by the agent"

    _write_driver()
    try:
        proc = _run_go(
            ["test", "-run", "TestBench", "-v", "-count=1", "-timeout=120s", "./"],
            timeout=600,
        )
    finally:
        _remove_driver()
    return proc


def _assert_marker(proc, marker):
    combined = (proc.stdout or "") + "\n" + (proc.stderr or "")
    assert proc.returncode == 0, (
        f"benchmark driver `go test` failed (rc={proc.returncode}).\n"
        f"STDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )
    assert marker in combined, (
        f"expected marker {marker!r} not found in driver output.\n"
        f"STDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )


class TestGoTestifyPatterns:
    """Verify the IPv4 CIDR membership classifier and its testify suite."""

    REPO_DIR = _find_repo_dir("/workspace/terraform")

    # ------------------------------------------------------------------
    # L1: deliverable files exist and are minimally well-formed
    # ------------------------------------------------------------------
    def test_cidrmatch_source_exists(self):
        """cidrmatch.go must exist in the ipaddr package and declare IPv4InCIDR."""
        p = os.path.join(IPADDR_DIR, "cidrmatch.go")
        assert os.path.isfile(p), f"missing deliverable {p}"
        with open(p) as f:
            content = f.read()
        assert "package ipaddr" in content, "cidrmatch.go must be in package ipaddr"
        assert "func IPv4InCIDR" in content, (
            "cidrmatch.go must declare the exported IPv4InCIDR function"
        )

    def test_cidrmatch_test_exists(self):
        """cidrmatch_test.go (the agent's testify suite) must exist & target the func."""
        p = os.path.join(IPADDR_DIR, "cidrmatch_test.go")
        assert os.path.isfile(p), f"missing deliverable {p}"
        with open(p) as f:
            content = f.read()
        assert "package ipaddr" in content, "cidrmatch_test.go must be in package ipaddr"
        assert "TestIPv4InCIDR" in content, (
            "cidrmatch_test.go must contain the mandated TestIPv4InCIDR launcher"
        )
        assert "testify" in content, (
            "the acceptance criteria require the test to use stretchr/testify"
        )

    def test_package_compiles(self):
        """The ipaddr package must still build with the new file added."""
        proc = _run_go(["build", "./"], timeout=600)
        assert proc.returncode == 0, (
            f"`go build ./` failed:\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
        )

    # ------------------------------------------------------------------
    # L2: independent dynamic execution of IPv4InCIDR
    # ------------------------------------------------------------------
    def test_slash8_membership(self, driver_run):
        """/8 block: inside, outside, network and broadcast addresses classified correctly."""
        _assert_marker(driver_run, "BENCH_OK_slash8")

    def test_slash24_membership(self, driver_run):
        """/24 block: network address and last (.255) address are inside; neighbors outside."""
        _assert_marker(driver_run, "BENCH_OK_slash24")

    def test_non_aligned_network(self, driver_run):
        """A /26 given with a non-base address must be masked to its true network range."""
        _assert_marker(driver_run, "BENCH_OK_nonaligned")

    def test_slash_zero_contains_all(self, driver_run):
        """/0 contains every valid IPv4 regardless of the CIDR's base address."""
        _assert_marker(driver_run, "BENCH_OK_slash0")

    def test_slash32_exact_only(self, driver_run):
        """/32 contains only the single exact address; off-by-one neighbors are outside."""
        _assert_marker(driver_run, "BENCH_OK_slash32")

    def test_prefix_is_honored(self, driver_run):
        """Membership respects the prefix length (a prefix-ignoring stub fails these)."""
        _assert_marker(driver_run, "BENCH_OK_prefix_honored")

    def test_invalid_ip_errors(self, driver_run):
        """Out-of-range / malformed / empty IPv4 inputs return (false, non-nil error)."""
        _assert_marker(driver_run, "BENCH_OK_invalid_ip")

    def test_invalid_cidr_errors(self, driver_run):
        """Missing '/', prefix outside 0..32, non-numeric prefix, bad network octet -> error."""
        _assert_marker(driver_run, "BENCH_OK_invalid_cidr")

    def test_ipv6_rejected(self, driver_run):
        """IPv6 address, IPv6 CIDR, and ipv4-mapped IPv6 are invalid (non-nil error)."""
        _assert_marker(driver_run, "BENCH_OK_ipv6_rejected")

    def test_no_panic_and_deterministic(self, driver_run):
        """A mix of valid/invalid inputs never panics and is deterministic across calls."""
        _assert_marker(driver_run, "BENCH_OK_no_panic_det")

    # ------------------------------------------------------------------
    # L2: the agent's own testify suite must pass under the mandated command
    # ------------------------------------------------------------------
    def test_agent_testify_suite_passes(self):
        """`go test ./internal/ipaddr/ -run TestIPv4InCIDR -v` (mandated command) must pass."""
        proc = _run_go(
            ["test", "-run", "TestIPv4InCIDR", "-v", "-count=1", "-timeout=120s", "./"],
            timeout=600,
        )
        out = (proc.stdout or "") + "\n" + (proc.stderr or "")
        assert proc.returncode == 0, (
            f"mandated testify command failed:\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
        )
        assert "TestIPv4InCIDR" in out, (
            "TestIPv4InCIDR launcher did not run; output:\n" + out
        )
        assert "no tests to run" not in out, (
            "TestIPv4InCIDR matched nothing:\n" + out
        )
        assert "ok" in out or "PASS" in out, "suite did not pass:\n" + out
