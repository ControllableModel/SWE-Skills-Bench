"""
Test for 'go-testify-patterns' skill (variant ext4) — IPv4 CIDR Membership
Classifier in the vendored `internal/ipaddr` package of hashicorp/terraform.

Variant task summary
--------------------
The agent must add a self-contained, network-free classifier to the existing
`ipaddr` package:

    // internal/ipaddr/cidrmatch.go
    func IPv4InCIDR(ip string, cidr string) (bool, error)

plus a deterministic testify-based test file
`internal/ipaddr/cidrmatch_test.go` whose top-level launcher is
`TestIPv4InCIDR`, runnable via the mandated command:

    go test ./internal/ipaddr/ -run TestIPv4InCIDR -v

Semantics required by the doc:
  - membership decided by masking the high `prefix` bits;
  - network address and broadcast/last address are BOTH inside;
  - `/0` contains every valid IPv4, `/32` only the exact address;
  - invalid ip / invalid cidr (missing '/', prefix outside 0..32,
    bad/out-of-range octet) and any IPv6 input -> (false, non-nil error),
    never a panic.

Verification strategy (discriminative power)
-------------------------------------------
Rather than trusting the agent's own test file, the L2 cases write an
INDEPENDENT Go test file (`zz_bench_cidrmatch_test.go`) into the `ipaddr`
package that calls `IPv4InCIDR` directly with carefully chosen vectors and
deep-validates the returned (bool, error). It uses only the Go standard
library, so it compiles regardless of whether testify is wired as a direct
module dependency. Each sub-test prints a unique BENCH_OK marker the python
layer asserts on. The driver file is removed in teardown.

A naive/stub implementation cannot pass: e.g. one that always returns true,
ignores the prefix length, treats the broadcast address as outside, fails to
reject out-of-range octets, or panics on IPv6 input each fails a distinct
marker. The agent's own mandated testify command is also exercised separately.
"""

