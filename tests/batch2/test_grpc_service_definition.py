"""Tests for the `grpc-service-definition` skill (variant ext2).

Skill / task: Tighten range-request validation in etcd's v3 KV service.
The guard `checkRangeRequest` in
`server/etcdserver/api/v3rpc/key.go` is the single place that screens incoming
`Range` RPCs before they reach storage. The variant task extends this guard so
that, in addition to the existing empty-key and invalid-sort-option rejections,
it ALSO rejects:

  * an inverted/empty interval: a non-empty `RangeEnd` that is lexicographically
    smaller than `Key` (e.g. Key="b", RangeEnd="a");
  * a negative pagination `Limit`.

while continuing to ACCEPT:

  * the forward range Key="a", RangeEnd="b";
  * the single-key form (empty RangeEnd);
  * the all-keys form (RangeEnd == the single zero byte "\\x00");
  * the degenerate equal form Key == RangeEnd;
  * a zero `Limit` ("no limit") and any positive `Limit`.

Contract details that MUST hold:
  * each new rejection surfaces as the SAME over-the-wire classification etcd
    already uses for malformed input (codes.InvalidArgument, matching the
    `.Error()` of the existing empty-key / invalid-sort errors) -- not an
    opaque/unknown classification and not a plain Go error;
  * a fully valid request returns nil;
  * the empty-key check takes PRECEDENCE over the new bound/limit checks (an
    empty key stays an empty-key error regardless of its other fields);
  * every existing `TestCheckRangeRequest` case keeps passing unchanged.

Verification strategy
---------------------
L1 checks the deliverable files exist and remain minimally well-formed (the
guard + its mapping table + the canonical existing test still present).

L2 drives the repo's native Go toolchain. The discriminative L2 cases do NOT
trust test files the agent may have written: this module copies an *independent*
probe test (`zz_skillprobe_range_test.go`) into the `v3rpc` package, which calls
the unexported `checkRangeRequest` directly and deep-validates, for every
documented case, the returned error's identity and its gRPC status code. A naive
implementation -- one that never rejects inverted ranges / negative limits, that
rejects accepted forms, that returns a plain Go error or the wrong classification,
or that lets the bound/limit checks shadow the empty-key check -- fails these
probes.
"""

import os
import subprocess
import textwrap

import pytest

def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/etcd")
PKG_REL = "etcdserver/api/v3rpc"
SERVER_DIR = os.path.join(REPO_DIR, "server")
PKG_DIR = os.path.join(SERVER_DIR, PKG_REL)
KEY_GO = os.path.join(PKG_DIR, "key.go")
KEY_TEST_GO = os.path.join(PKG_DIR, "key_test.go")

PROBE_BASENAME = "zz_skillprobe_range_test.go"
PROBE_PATH = os.path.join(PKG_DIR, PROBE_BASENAME)

GO_ENV = {
    **os.environ,
    "GOFLAGS": os.environ.get("GOFLAGS", ""),
    "CGO_ENABLED": "0",
}


def _go(args, timeout=600):
    """Run a `go` command from the server module dir."""
    return subprocess.run(
        ["go"] + args,
        cwd=SERVER_DIR,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=GO_ENV,
    )


# --------------------------------------------------------------------------
# Independent probe test installed into the package.
#
# It lives in `package v3rpc` so it can call the unexported `checkRangeRequest`.
# Each requirement is a hard assertion driven entirely by field values; the
# whole thing must compile AND pass.
# --------------------------------------------------------------------------
PROBE_SOURCE = textwrap.dedent(
    '''\
    // Code generated by the skill benchmark. DO NOT keep.
    package v3rpc

    import (
    	"testing"

    	"google.golang.org/grpc/codes"
    	"google.golang.org/grpc/status"

    	pb "go.etcd.io/etcd/api/v3/etcdserverpb"
    	"go.etcd.io/etcd/api/v3/v3rpc/rpctypes"
    )

    // codeOf returns the gRPC status code for an error, or codes.OK for nil
    // and codes.Unknown for a non-status error (a plain Go error).
    func skillProbeCodeOf(err error) codes.Code {
    	if err == nil {
    		return codes.OK
    	}
    	st, ok := status.FromError(err)
    	if !ok {
    		return codes.Unknown
    	}
    	return st.Code()
    }

    // The classification etcd already uses for malformed input. Both
    // ErrGRPCEmptyKey and ErrGRPCInvalidSortOption are codes.InvalidArgument.
    func skillProbeMalformedCode(t *testing.T) codes.Code {
    	t.Helper()
    	ek := skillProbeCodeOf(rpctypes.ErrGRPCEmptyKey)
    	is := skillProbeCodeOf(rpctypes.ErrGRPCInvalidSortOption)
    	if ek != is {
    		t.Fatalf("baseline malformed codes differ: emptyKey=%v invalidSort=%v", ek, is)
    	}
    	if ek == codes.Unknown || ek == codes.OK {
    		t.Fatalf("baseline malformed code is not a specific classification: %v", ek)
    	}
    	return ek
    }

    func skillProbeReq(key, rangeEnd string, limit int64) *pb.RangeRequest {
    	r := &pb.RangeRequest{
    		Key:        []byte(key),
    		SortOrder:  pb.RangeRequest_NONE,
    		SortTarget: pb.RangeRequest_KEY,
    		Limit:      limit,
    	}
    	if rangeEnd != "" {
    		r.RangeEnd = []byte(rangeEnd)
    	}
    	return r
    }

    // SKILLPROBE A: an inverted interval (non-empty RangeEnd < Key) is rejected
    // with the malformed-input classification.
    func TestSkillProbe_InvertedRangeRejected(t *testing.T) {
    	want := skillProbeMalformedCode(t)
    	got := checkRangeRequest(skillProbeReq("b", "a", 0))
    	if got == nil {
    		t.Fatalf("inverted range Key=b RangeEnd=a: got nil, want rejection")
    	}
    	if skillProbeCodeOf(got) != want {
    		t.Fatalf("inverted range code = %v, want %v (err=%v)", skillProbeCodeOf(got), want, got)
    	}
    	if skillProbeCodeOf(got) == codes.Unknown {
    		t.Fatalf("inverted range produced opaque Unknown classification: %v", got)
    	}
    	// A second, longer inverted pair to defeat a same-length-only check.
    	got2 := checkRangeRequest(skillProbeReq("zzz", "zza", 0))
    	if got2 == nil || skillProbeCodeOf(got2) != want {
    		t.Fatalf("inverted range Key=zzz RangeEnd=zza: got %v (code %v), want malformed rejection", got2, skillProbeCodeOf(got2))
    	}
    }

    // SKILLPROBE B: the documented ACCEPTED range forms must return nil.
    func TestSkillProbe_AcceptedRangeForms(t *testing.T) {
    	cases := []struct {
    		name     string
    		key      string
    		rangeEnd string
    	}{
    		{"forward", "a", "b"},
    		{"singleKey", "a", ""},
    		{"allKeysZeroByte", "a", "\\x00"},
    		{"equal", "a", "a"},
    	}
    	for _, c := range cases {
    		if err := checkRangeRequest(skillProbeReq(c.key, c.rangeEnd, 0)); err != nil {
    			t.Fatalf("%s (Key=%q RangeEnd=%q): got %v, want nil (accepted)", c.name, c.key, c.rangeEnd, err)
    		}
    	}
    	// Explicitly: RangeEnd == single zero byte means "to end of keyspace".
    	if err := checkRangeRequest(skillProbeReq("m", "\\x00", 0)); err != nil {
    		t.Fatalf("all-keys form Key=m RangeEnd=\\x00: got %v, want nil", err)
    	}
    }

    // SKILLPROBE C: a negative Limit is rejected with the malformed classification;
    // zero and positive limits are accepted.
    func TestSkillProbe_LimitValidation(t *testing.T) {
    	want := skillProbeMalformedCode(t)

    	neg := checkRangeRequest(skillProbeReq("a", "b", -1))
    	if neg == nil {
    		t.Fatalf("Limit=-1: got nil, want rejection")
    	}
    	if skillProbeCodeOf(neg) != want {
    		t.Fatalf("Limit=-1 code = %v, want %v (err=%v)", skillProbeCodeOf(neg), want, neg)
    	}
    	neg2 := checkRangeRequest(skillProbeReq("a", "", -100))
    	if neg2 == nil || skillProbeCodeOf(neg2) != want {
    		t.Fatalf("Limit=-100: got %v (code %v), want malformed rejection", neg2, skillProbeCodeOf(neg2))
    	}

    	if err := checkRangeRequest(skillProbeReq("a", "b", 0)); err != nil {
    		t.Fatalf("Limit=0 (no limit): got %v, want nil", err)
    	}
    	if err := checkRangeRequest(skillProbeReq("a", "b", 5)); err != nil {
    		t.Fatalf("Limit=5: got %v, want nil", err)
    	}
    	if err := checkRangeRequest(skillProbeReq("a", "", 1000000)); err != nil {
    		t.Fatalf("Limit=1000000: got %v, want nil", err)
    	}
    }

    // SKILLPROBE D: the empty-key check takes PRECEDENCE -- an empty key stays an
    // empty-key error regardless of other (otherwise-rejectable) fields.
    func TestSkillProbe_EmptyKeyPrecedence(t *testing.T) {
    	// Empty key combined with an inverted interval AND a negative limit.
    	got := checkRangeRequest(skillProbeReq("", "a", -1))
    	if got == nil {
    		t.Fatalf("empty key: got nil, want empty-key rejection")
    	}
    	if got.Error() != rpctypes.ErrGRPCEmptyKey.Error() {
    		t.Fatalf("empty key with bad bounds/limit -> %v, want ErrGRPCEmptyKey", got)
    	}
    	// Plain empty key, otherwise valid.
    	got2 := checkRangeRequest(skillProbeReq("", "", 0))
    	if got2 == nil || got2.Error() != rpctypes.ErrGRPCEmptyKey.Error() {
    		t.Fatalf("plain empty key -> %v, want ErrGRPCEmptyKey", got2)
    	}
    }

    // SKILLPROBE E: existing invalid-sort-option behavior is preserved.
    func TestSkillProbe_InvalidSortPreserved(t *testing.T) {
    	bad := &pb.RangeRequest{Key: []byte("a"), SortOrder: 200, SortTarget: pb.RangeRequest_KEY}
    	got := checkRangeRequest(bad)
    	if got == nil || got.Error() != rpctypes.ErrGRPCInvalidSortOption.Error() {
    		t.Fatalf("bad sort order -> %v, want ErrGRPCInvalidSortOption", got)
    	}
    	bad2 := &pb.RangeRequest{Key: []byte("a"), SortOrder: pb.RangeRequest_ASCEND, SortTarget: 100}
    	got2 := checkRangeRequest(bad2)
    	if got2 == nil || got2.Error() != rpctypes.ErrGRPCInvalidSortOption.Error() {
    		t.Fatalf("bad sort target -> %v, want ErrGRPCInvalidSortOption", got2)
    	}
    }

    // SKILLPROBE F: a fully valid request returns nil (regression / sanity).
    func TestSkillProbe_FullyValidAccepted(t *testing.T) {
    	if err := checkRangeRequest(skillProbeReq("a", "b", 5)); err != nil {
    		t.Fatalf("fully valid request -> %v, want nil", err)
    	}
    }

    // SKILLPROBE G: every rejection emitted by the guard must be a proper gRPC
    // status error with the malformed-input classification -- never a plain Go
    // error and never an opaque Unknown.
    func TestSkillProbe_RejectionsAreGrpcStatus(t *testing.T) {
    	want := skillProbeMalformedCode(t)
    	rejecting := []*pb.RangeRequest{
    		skillProbeReq("b", "a", 0),  // inverted
    		skillProbeReq("a", "b", -1), // negative limit
    	}
    	for i, r := range rejecting {
    		err := checkRangeRequest(r)
    		if err == nil {
    			t.Fatalf("case %d: expected a rejection, got nil", i)
    		}
    		st, ok := status.FromError(err)
    		if !ok {
    			t.Fatalf("case %d: rejection is not a gRPC status error: %v", i, err)
    		}
    		if st.Code() != want {
    			t.Fatalf("case %d: rejection code = %v, want %v", i, st.Code(), want)
    		}
    		if st.Code() == codes.Unknown {
    			t.Fatalf("case %d: rejection collapsed to Unknown: %v", i, err)
    		}
    	}
    }
    '''
)


@pytest.fixture(scope="module", autouse=True)
def _install_probe_and_cleanup():
    """Install the independent probe test into the package, remove afterwards."""
    assert os.path.isdir(PKG_DIR), f"package dir missing: {PKG_DIR}"
    with open(PROBE_PATH, "w") as fh:
        fh.write(PROBE_SOURCE)
    try:
        yield
    finally:
        try:
            os.remove(PROBE_PATH)
        except OSError:
            pass


class TestGrpcServiceDefinition:
    REPO_DIR = _find_repo_dir("/workspace/etcd")

    # ---------------------- L1: deliverables exist / well-formed -------------

    def test_key_go_exists(self):
        """L1: the guard source file `key.go` exists."""
        assert os.path.isfile(KEY_GO), f"missing {KEY_GO}"

    def test_key_test_go_exists(self):
        """L1: the test file `key_test.go` exists."""
        assert os.path.isfile(KEY_TEST_GO), f"missing {KEY_TEST_GO}"

    def test_key_go_defines_checkrangerequest(self):
        """L1: `key.go` still defines `checkRangeRequest` and references RangeEnd/Limit."""
        with open(KEY_GO) as fh:
            src = fh.read()
        assert "func checkRangeRequest(" in src, "checkRangeRequest definition not found"
        # The new behavior must consult RangeEnd and Limit (field-driven, not a stub).
        assert "RangeEnd" in src, "checkRangeRequest does not reference RangeEnd"
        assert "Limit" in src, "checkRangeRequest does not reference Limit"

    def test_key_test_defines_checkrangerequest_test(self):
        """L1: `key_test.go` still contains the canonical TestCheckRangeRequest."""
        with open(KEY_TEST_GO) as fh:
            src = fh.read()
        assert "func TestCheckRangeRequest(" in src, "TestCheckRangeRequest not found in key_test.go"

    # ---------------------- L2: native build + behavior ----------------------

    def test_package_builds(self):
        """L2: the v3rpc package compiles (agent did not break the build)."""
        res = _go(["build", "./" + PKG_REL + "/..."])
        assert res.returncode == 0, (
            "go build failed:\n" + res.stdout + "\n" + res.stderr
        )

    def test_vet_package(self):
        """L2: `go vet` passes on the package when it is able to run."""
        res = _go(["vet", "./" + PKG_REL + "/"])
        if res.returncode != 0:
            combined = (res.stdout + res.stderr).lower()
            if (
                "cannot find" not in combined
                and "timeout" not in combined
                and "dial tcp" not in combined
                and "no such host" not in combined
            ):
                assert res.returncode == 0, (
                    "go vet reported problems:\n" + res.stdout + "\n" + res.stderr
                )

    def test_existing_checkrangerequest_passes(self):
        """L2: the canonical TestCheckRangeRequest (existing cases) must still pass.

        This is the variant's native acceptance command.
        """
        res = _go(
            ["test", "./" + PKG_REL + "/", "-run", "TestCheckRangeRequest",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, "TestCheckRangeRequest failed:\n" + out
        assert "PASS" in out, "no PASS marker in TestCheckRangeRequest output:\n" + out
        assert "--- FAIL" not in out, "a subtest FAILED:\n" + out

    def test_probe_inverted_range_rejected(self):
        """L2: an inverted interval (RangeEnd < Key) is rejected as malformed input."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillProbe_InvertedRangeRejected$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "inverted-range probe failed (guard does not reject RangeEnd < Key with "
            "the malformed-input classification):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_accepted_range_forms(self):
        """L2: forward / single-key / all-keys / equal ranges are accepted (nil)."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillProbe_AcceptedRangeForms$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "accepted-range-forms probe failed (a valid range form was wrongly "
            "rejected -- likely an over-broad bound check):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_limit_validation(self):
        """L2: negative Limit rejected; zero and positive Limit accepted."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillProbe_LimitValidation$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "limit-validation probe failed (negative limit not rejected, or "
            "zero/positive limit wrongly rejected):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_empty_key_precedence(self):
        """L2: the empty-key check takes precedence over the new bound/limit checks."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillProbe_EmptyKeyPrecedence$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "empty-key-precedence probe failed (an empty-key request no longer "
            "surfaces ErrGRPCEmptyKey when other fields are also invalid):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_invalid_sort_preserved(self):
        """L2: existing invalid-sort-option rejection is preserved unchanged."""
