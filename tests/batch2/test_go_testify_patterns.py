"""
Test for 'go-testify-patterns' skill (variant ext2) — Token-Aware Name
Suggestion Ranker for hashicorp/terraform's `internal/didyoumean` package.

Variant task summary
---------------------
The agent must add a self-contained, network-free ranking helper to the existing
`didyoumean` package:

    func RankSuggestions(given string, candidates []string, maxResults int) []string

returning the candidates whose case-insensitive Levenshtein distance to `given`
is strictly less than 3, ordered ascending by distance with a STABLE tie-break
that preserves the original input order, capped at `maxResults` (where
`maxResults <= 0` means "no cap"). An exact case-insensitive match (distance 0)
must rank first. Duplicates are kept independently. Empty / no-qualifier inputs
return an empty result without panicking.

Deliverables:
  - internal/didyoumean/rank.go        (new, package didyoumean)
  - internal/didyoumean/rank_test.go   (new, testify-based; the mandated command
                                        `go test ./internal/didyoumean/
                                        -run TestRankSuggestions -v` must pass)

Verification strategy (discriminative power)
--------------------------------------------
Rather than trusting the agent's own rank_test.go, the L2 cases inject an
INDEPENDENT Go test file (`zz_bench_rank_test.go`) into the didyoumean package
that calls `RankSuggestions` directly and deep-validates real behavior:
distance ordering, the strict `< 3` threshold (distance-3 excluded), exact-match
case-insensitive ranking, stable tie-break, `maxResults` capping vs. no-cap,
duplicate handling, and empty / no-qualifier safety. Each sub-test prints a
unique OK marker the python layer asserts on. The driver file is removed in
teardown. A naive implementation (returns input unchanged, ignores distance,
hardcodes output, drops the threshold, de-duplicates, or sorts unstably) cannot
produce every marker. Finally the agent's own mandated testify command is run.
"""

