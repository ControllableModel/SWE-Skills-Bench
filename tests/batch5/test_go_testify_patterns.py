"""
Test for 'go-testify-patterns' skill (variant ext5) — Ordered String-Set Diff
Helper for the collections package (hashicorp/terraform).

Variant task: the agent must add a self-contained, network-free helper
`internal/collections/strdiff.go` (package `collections`) exposing:

    type StringSetDiff struct {
        Added   []string
        Removed []string
        Common  []string
    }
    func DiffStringSets(before []string, after []string) StringSetDiff

plus a testify-based test `internal/collections/strdiff_test.go` whose launcher
is `TestDiffStringSets`. The three result slices must be set-based (deduped),
sorted ascending, non-nil even when empty, order-independent, and deterministic.

Verification strategy (discriminative power): rather than trusting the agent's
own test file, the L2 cases inject an INDEPENDENT Go test file
(`zz_bench_strdiff_test.go`) into the collections package that calls
`DiffStringSets` directly and deep-validates real behavior (set membership
partition, dedup, ascending sort, non-nil empty slices, empty-input handling,
order independence, determinism). That file is removed in teardown. Each Go
sub-test prints a unique OK marker the python layer asserts on, so a naive /
hardcoded / file-only / input-ignoring implementation cannot pass. A final L2
case also drives the doc's mandated native command on the agent's own suite:

    go test ./internal/collections/ -run TestDiffStringSets -v
"""

