"""Tests for the `grpc-service-definition` skill (variant ext5).

Skill / task: Pin down the duplicate-key / overlap-detection contract of
`checkIntervals` in etcd's v3 KV RPC server
(`server/etcdserver/api/v3rpc/key.go`). `checkIntervals` walks the operations
of a transaction branch and MUST reject any operation set in which two writes
touch the same key, or a write overlaps a delete range, surfacing the
*duplicate-key* over-the-wire classification (`rpctypes.ErrGRPCDuplicateKey`,
a `codes.InvalidArgument` status). The contract that must hold:

  * Two `Put`s on the same key            -> duplicate-key error.
  * `Put` inside a `DeleteRange [Key,End)` -> duplicate-key error.
  * `Put` equal to a single-key `Delete`   -> duplicate-key error.
  * Distinct puts, disjoint delete ranges  -> accepted (nil error).
  * The same key in the then-branch AND the else-branch of one nested txn
    is mutually exclusive at runtime        -> accepted.
  * Empty operation slice                   -> accepted.
  * Detection is driven by keys/ranges, never by string-matching messages,
    and the rejection is always the duplicate-key classification (never a
    plain Go error or an opaque/unknown status).

Verification strategy
---------------------
L1 checks the deliverable files (`key.go`, `key_test.go`) exist and remain
well-formed (still define `checkIntervals` / a `TestCheckIntervals`).

L2 drives the repo's native Go toolchain. The discriminative L2 cases do NOT
trust a test the agent itself may have written: this module installs an
*independent* probe test (`zz_skillprobe_key_test.go`) into the `v3rpc`
package. The probe lives in `package v3rpc`, so it calls the unexported
`checkIntervals` directly with hand-built `[]*pb.RequestOp` values
(`pb.RequestOp_RequestPut`, `pb.RequestOp_RequestDeleteRange`,
`pb.RequestOp_RequestTxn`) and deep-validates, for every scenario, the
returned error identity (`errors.Is` against `rpctypes.ErrGRPCDuplicateKey` /
its gRPC status code) or nil. A naive implementation that always accepts,
always rejects, ignores delete ranges, treats then/else as a conflict, or
returns a generic error instead of the duplicate-key classification fails
these probes.
"""

import os
import subprocess
import textwrap

import pytest

def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/etcd")
PKG_REL = "etcdserver/api/v3rpc"
SERVER_DIR = os.path.join(REPO_DIR, "server")
PKG_DIR = os.path.join(SERVER_DIR, PKG_REL)
KEY_GO = os.path.join(PKG_DIR, "key.go")
KEY_TEST_GO = os.path.join(PKG_DIR, "key_test.go")

PROBE_BASENAME = "zz_skillprobe_key_test.go"
PROBE_PATH = os.path.join(PKG_DIR, PROBE_BASENAME)

GO_ENV = {
    **os.environ,
    "GOFLAGS": os.environ.get("GOFLAGS", ""),
    "CGO_ENABLED": "0",
}


def _go(args, timeout=600):
    """Run a `go` command from the server module dir."""
    return subprocess.run(
        ["go"] + args,
        cwd=SERVER_DIR,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=GO_ENV,
    )


# --------------------------------------------------------------------------
# Independent probe test installed into the package.
#
# It lives in `package v3rpc` so it can call the unexported `checkIntervals`.
# Each scenario is a hard assertion built from real proto operations; the
# whole file must compile AND pass.
# --------------------------------------------------------------------------
PROBE_SOURCE = textwrap.dedent(
    '''\
    // Code generated by the skill benchmark. DO NOT keep.
    package v3rpc

    import (
    	stderrors "errors"
    	"testing"

    	"google.golang.org/grpc/codes"
    	"google.golang.org/grpc/status"

    	pb "go.etcd.io/etcd/api/v3/etcdserverpb"
    	"go.etcd.io/etcd/api/v3/v3rpc/rpctypes"
    )

    // --- builders for proto request ops ----------------------------------

    func skProbePut(key string) *pb.RequestOp {
    	return &pb.RequestOp{
    		Request: &pb.RequestOp_RequestPut{
    			RequestPut: &pb.PutRequest{Key: []byte(key)},
    		},
    	}
    }

    // skProbeDel builds a delete op. If rangeEnd == "" it is a single-key delete.
    func skProbeDel(key, rangeEnd string) *pb.RequestOp {
    	d := &pb.DeleteRangeRequest{Key: []byte(key)}
    	if rangeEnd != "" {
    		d.RangeEnd = []byte(rangeEnd)
    	}
    	return &pb.RequestOp{
    		Request: &pb.RequestOp_RequestDeleteRange{RequestDeleteRange: d},
    	}
    }

    func skProbeTxn(then, els []*pb.RequestOp) *pb.RequestOp {
    	return &pb.RequestOp{
    		Request: &pb.RequestOp_RequestTxn{
    			RequestTxn: &pb.TxnRequest{Success: then, Failure: els},
    		},
    	}
    }

    // skProbeIsDup reports whether err is exactly the duplicate-key
    // classification: the rpctypes duplicate-key error, carrying the
    // InvalidArgument transport code -- not a plain Go error, not Unknown.
    func skProbeIsDup(err error) bool {
    	if err == nil {
    		return false
    	}
    	if stderrors.Is(err, rpctypes.ErrGRPCDuplicateKey) {
    		return true
    	}
    	if err.Error() != rpctypes.ErrGRPCDuplicateKey.Error() {
    		return false
    	}
    	st, ok := status.FromError(err)
    	return ok && st.Code() == codes.InvalidArgument
    }

    // SKILLPROBE 1: two puts on the same key must be rejected as duplicate-key.
    func TestSkillProbe_TwoPutsSameKey(t *testing.T) {
    	ops := []*pb.RequestOp{skProbePut("k"), skProbePut("k")}
    	_, _, err := checkIntervals(ops)
    	if !skProbeIsDup(err) {
    		t.Fatalf("two puts on \\"k\\": err=%v, want ErrGRPCDuplicateKey", err)
    	}
    	if st, ok := status.FromError(err); !ok || st.Code() != codes.InvalidArgument {
    		t.Fatalf("two puts on \\"k\\": code mismatch (%v), want InvalidArgument", err)
    	}
    }

    // SKILLPROBE 2: a put that falls inside a delete RANGE must be rejected.
    func TestSkillProbe_PutInsideDeleteRange(t *testing.T) {
    	// Put "b" overlaps DeleteRange ["a","c").
    	ops := []*pb.RequestOp{skProbePut("b"), skProbeDel("a", "c")}
    	_, _, err := checkIntervals(ops)
    	if !skProbeIsDup(err) {
    		t.Fatalf("put \\"b\\" inside del [a,c): err=%v, want ErrGRPCDuplicateKey", err)
    	}

    	// Order independence: delete listed first.
    	ops2 := []*pb.RequestOp{skProbeDel("a", "c"), skProbePut("b")}
    	_, _, err2 := checkIntervals(ops2)
    	if !skProbeIsDup(err2) {
    		t.Fatalf("del [a,c) then put \\"b\\": err=%v, want ErrGRPCDuplicateKey", err2)
    	}
    }

    // SKILLPROBE 3: a put equal to a single-key delete (empty RangeEnd) is rejected.
    func TestSkillProbe_PutEqualsSingleDelete(t *testing.T) {
    	ops := []*pb.RequestOp{skProbePut("x"), skProbeDel("x", "")}
    	_, _, err := checkIntervals(ops)
    	if !skProbeIsDup(err) {
    		t.Fatalf("put \\"x\\" + del \\"x\\": err=%v, want ErrGRPCDuplicateKey", err)
    	}
    }

    // SKILLPROBE 4: distinct puts + disjoint delete range are accepted.
    func TestSkillProbe_DisjointAccepted(t *testing.T) {
    	// Put "a" + DeleteRange ["b","c") -> no overlap.
    	ops := []*pb.RequestOp{skProbePut("a"), skProbeDel("b", "c")}
    	puts, _, err := checkIntervals(ops)
    	if err != nil {
    		t.Fatalf("put \\"a\\" + del [b,c): err=%v, want nil", err)
    	}
    	if _, ok := puts["a"]; !ok {
    		t.Fatalf("returned put set %v missing \\"a\\"", puts)
    	}

    	// Several distinct puts, no deletes.
    	ops2 := []*pb.RequestOp{skProbePut("p"), skProbePut("q"), skProbePut("r")}
    	puts2, _, err2 := checkIntervals(ops2)
    	if err2 != nil {
    		t.Fatalf("distinct puts p,q,r: err=%v, want nil", err2)
    	}
    	if len(puts2) != 3 {
    		t.Fatalf("distinct puts: put set %v, want 3 keys", puts2)
    	}
    }

    // SKILLPROBE 5: empty operation slice is accepted with empty sets.
    func TestSkillProbe_EmptyAccepted(t *testing.T) {
    	puts, _, err := checkIntervals(nil)
    	if err != nil {
    		t.Fatalf("nil ops: err=%v, want nil", err)
    	}
    	if len(puts) != 0 {
    		t.Fatalf("nil ops: put set %v, want empty", puts)
    	}

    	puts2, _, err2 := checkIntervals([]*pb.RequestOp{})
    	if err2 != nil || len(puts2) != 0 {
    		t.Fatalf("empty ops: err=%v puts=%v, want nil/empty", err2, puts2)
    	}
    }

    // SKILLPROBE 6: same key in then-branch AND else-branch of ONE nested txn
    // is mutually exclusive at runtime -> must be ACCEPTED.
    func TestSkillProbe_NestedThenElseExclusive(t *testing.T) {
    	nested := skProbeTxn(
    		[]*pb.RequestOp{skProbePut("shared")}, // then
    		[]*pb.RequestOp{skProbePut("shared")}, // else
    	)
    	puts, _, err := checkIntervals([]*pb.RequestOp{nested})
    	if err != nil {
    		t.Fatalf("then/else both put \\"shared\\": err=%v, want nil (branches exclusive)", err)
    	}
    	if _, ok := puts["shared"]; !ok {
    		t.Fatalf("nested put set %v missing \\"shared\\"", puts)
    	}
    }

    // SKILLPROBE 7: a real conflict WITHIN the same nested branch is still rejected.
    func TestSkillProbe_NestedSameBranchConflict(t *testing.T) {
    	nested := skProbeTxn(
    		[]*pb.RequestOp{skProbePut("dup"), skProbePut("dup")}, // same branch dup
    		nil,
    	)
    	_, _, err := checkIntervals([]*pb.RequestOp{nested})
    	if !skProbeIsDup(err) {
    		t.Fatalf("same-branch dup put: err=%v, want ErrGRPCDuplicateKey", err)
    	}
    }

    // SKILLPROBE 8: a nested put overlapping an OUTER delete range is rejected.
    func TestSkillProbe_NestedPutOuterDelete(t *testing.T) {
    	nested := skProbeTxn([]*pb.RequestOp{skProbePut("m")}, nil)
    	ops := []*pb.RequestOp{skProbeDel("a", "z"), nested} // "m" inside [a,z)
    	_, _, err := checkIntervals(ops)
    	if !skProbeIsDup(err) {
    		t.Fatalf("nested put \\"m\\" overlapping outer del [a,z): err=%v, want ErrGRPCDuplicateKey", err)
    	}
    }

    // SKILLPROBE 9: the rejection is NEVER an opaque/unknown classification and
    // NEVER a plain Go error -- it is exactly the duplicate-key status.
    func TestSkillProbe_RejectionClassificationExact(t *testing.T) {
    	_, _, err := checkIntervals([]*pb.RequestOp{skProbePut("z"), skProbePut("z")})
    	if err == nil {
    		t.Fatalf("expected a rejection error, got nil")
    	}
    	st, ok := status.FromError(err)
    	if !ok {
    		t.Fatalf("rejection is a plain Go error (no gRPC status): %v", err)
    	}
    	if st.Code() == codes.Unknown {
    		t.Fatalf("rejection flattened to Unknown: %v", err)
    	}
    	if st.Code() != codes.InvalidArgument {
    		t.Fatalf("rejection code = %v, want InvalidArgument", st.Code())
    	}
    	if !stderrors.Is(err, rpctypes.ErrGRPCDuplicateKey) &&
    		err.Error() != rpctypes.ErrGRPCDuplicateKey.Error() {
    		t.Fatalf("rejection identity = %v, want ErrGRPCDuplicateKey", err)
    	}
    }

    // SKILLPROBE 10: detection is driven by keys/ranges, not message matching --
    // a put whose key equals a delete range's endpoint sits OUTSIDE [Key,End)
    // (half-open) and must be accepted.
    func TestSkillProbe_RangeEndpointExclusive(t *testing.T) {
    	// DeleteRange ["a","c"): key "c" is the exclusive end -> NOT overlapping.
    	ops := []*pb.RequestOp{skProbePut("c"), skProbeDel("a", "c")}
    	_, _, err := checkIntervals(ops)
    	if err != nil {
    		t.Fatalf("put \\"c\\" at exclusive end of [a,c): err=%v, want nil", err)
    	}

    	// But "a" (the inclusive start) IS inside -> rejected.
    	ops2 := []*pb.RequestOp{skProbePut("a"), skProbeDel("a", "c")}
    	_, _, err2 := checkIntervals(ops2)
    	if !skProbeIsDup(err2) {
    		t.Fatalf("put \\"a\\" at inclusive start of [a,c): err=%v, want ErrGRPCDuplicateKey", err2)
    	}
    }
    '''
)


@pytest.fixture(scope="module", autouse=True)
def _install_probe_and_cleanup():
    """Install the independent probe test into the package, remove afterwards."""
    assert os.path.isdir(PKG_DIR), f"package dir missing: {PKG_DIR}"
    with open(PROBE_PATH, "w") as fh:
        fh.write(PROBE_SOURCE)
    try:
        yield
    finally:
        try:
            os.remove(PROBE_PATH)
        except OSError:
            pass


class TestGrpcServiceDefinition:
    REPO_DIR = _find_repo_dir("/workspace/etcd")

    # ---------------------- L1: deliverables exist / well-formed -------------

    def test_key_go_exists(self):
        """L1: the production source file `key.go` exists."""
        assert os.path.isfile(KEY_GO), f"missing {KEY_GO}"

    def test_key_test_go_exists(self):
        """L1: the test file `key_test.go` exists."""
        assert os.path.isfile(KEY_TEST_GO), f"missing {KEY_TEST_GO}"

    def test_key_go_defines_checkintervals(self):
        """L1: `key.go` still defines `checkIntervals` and references the dup-key error."""
        with open(KEY_GO) as fh:
            src = fh.read()
        assert "func checkIntervals(" in src, "checkIntervals definition not found"
        assert "ErrGRPCDuplicateKey" in src, "ErrGRPCDuplicateKey not referenced in key.go"

    def test_key_test_defines_checkintervals_test(self):
        """L1: `key_test.go` contains a TestCheckIntervals pinning the contract."""
        with open(KEY_TEST_GO) as fh:
            src = fh.read()
        assert "func TestCheckIntervals(" in src, "TestCheckIntervals not found in key_test.go"
        # The agent's test must construct real request ops, not merely assert text.
        assert "RequestOp" in src, "key_test.go does not construct pb.RequestOp values"

    # ---------------------- L2: native build + behavior ----------------------

    def test_package_builds(self):
        """L2: the v3rpc package compiles (agent did not break the build)."""
        res = _go(["build", "./" + PKG_REL + "/..."])
        assert res.returncode == 0, (
            "go build failed:\n" + res.stdout + "\n" + res.stderr
        )

    def test_vet_package(self):
        """L2: `go vet` passes on the package when it is able to run."""
        res = _go(["vet", "./" + PKG_REL + "/"])
        if res.returncode != 0:
            combined = (res.stdout + res.stderr).lower()
            if (
                "cannot find" not in combined
                and "timeout" not in combined
                and "dial tcp" not in combined
                and "no such host" not in combined
            ):
                assert res.returncode == 0, (
                    "go vet reported problems:\n" + res.stdout + "\n" + res.stderr
                )

    def test_agent_checkintervals_test_passes(self):
        """L2: the agent's own native TestCheckIntervals must pass (acceptance command)."""
        res = _go(
            ["test", "./" + PKG_REL + "/", "-run", "TestCheckIntervals", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, "TestCheckIntervals failed:\n" + out
        assert "PASS" in out, "no PASS marker in TestCheckIntervals output:\n" + out
        assert "--- FAIL" not in out, "a subtest FAILED:\n" + out

    def test_probe_conflicts_rejected(self):
        """L2: every conflict scenario (same-key, in-range, point-delete) is rejected as dup-key."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillProbe_TwoPutsSameKey|TestSkillProbe_PutInsideDeleteRange|TestSkillProbe_PutEqualsSingleDelete)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "conflict-rejection probe failed (a real overlap was not rejected with "
            "the duplicate-key classification):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_disjoint_and_empty_accepted(self):
        """L2: disjoint puts/ranges and the empty op set are accepted with correct put sets."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillProbe_DisjointAccepted|TestSkillProbe_EmptyAccepted)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "acceptance probe failed (a non-overlapping / empty op set was wrongly "
            "rejected, or the returned put set is wrong):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_nested_then_else_exclusive(self):
        """L2: shared key across then/else of one nested txn is accepted; same-branch dup rejected."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillProbe_NestedThenElseExclusive|TestSkillProbe_NestedSameBranchConflict|TestSkillProbe_NestedPutOuterDelete)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "nested-txn probe failed (then/else mutual-exclusivity or nested "
            "conflict handling is wrong):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_rejection_classification_exact(self):
        """L2: rejections carry the duplicate-key InvalidArgument classification, never Unknown/plain."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillProbe_RejectionClassificationExact|TestSkillProbe_RangeEndpointExclusive)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "classification probe failed (rejection used a wrong/opaque error, or "
            "the half-open range boundary is mishandled):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_full_probe_suite_passes_together(self):
        """L2: the whole overlap-detection matrix passes in one native run (integration)."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillProbe_.*$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, "combined probe suite failed:\n" + out
        assert "--- FAIL" not in out, "at least one case FAILED:\n" + out
        assert "ok  " in out or "PASS" in out, "no success marker:\n" + out
