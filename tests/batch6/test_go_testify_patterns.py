"""
Test for 'go-testify-patterns' skill (variant ext6) — Dependency-Layer
Computer for the DAG package (hashicorp/terraform).

The agent must add a network-free, self-contained helper to the existing
`internal/dag` package:

    func DependencyLayers(nodes []string, dependsOn map[string][]string) ([][]string, error)

It groups node names into ordered, parallelizable layers:
  - Layer 0 = nodes with no in-set dependencies.
  - Layer k = nodes all of whose in-set deps are in layers 0..k-1, with at
    least one dep in layer k-1.
  - Names within a layer are sorted ascending (deterministic).
  - Nodes referenced in dependsOn values but not in `nodes` are ignored
    (treated as already-satisfied external references) and do not block.
  - Duplicate dependency entries collapse to one.
  - A cycle (restricted to `nodes`) returns a non-nil error AND a nil layer
    list (never panic / infinite loop).
  - Empty `nodes` returns a non-nil empty layer list and a nil error.

Verification strategy for discriminative power:
Rather than trusting the agent's own test file, the bulk of the L2 cases write
an INDEPENDENT Go test file (`zz_bench_layers_test.go`) into the `dag` package
that calls `DependencyLayers` directly and deep-validates the exact layering
(values, ordering, layer membership, cycle errors, external-ref handling,
de-dup, determinism). That file is removed in teardown. A naive implementation
(returns a single flat layer, ignores ordering, panics/loops on cycles, fails
to ignore external refs, or is non-deterministic) cannot pass these markers.
Finally, the agent's own mandated testify command must also pass.
"""

