"""Tests for the `grpc-service-definition` skill (variant ext6).

Skill / task: Pin down the client-side cancellation classifier in etcd's v3
RPC layer. The unexported helper `isClientCtxErr(ctxErr, err)` (in
`server/etcdserver/api/v3rpc/util.go`) decides whether a streaming-handler
error should be attributed to the client (cancel / deadline / disconnect)
rather than to a genuine server fault. The agent must add a test (e.g.
`TestIsClientCtxErr` in `util_test.go`) that pins the full classification
contract, only touching `util.go` if a real defect is found:

  * non-nil ctxErr  + any err                       -> true
  * nil    ctxErr   + Canceled-classified err        -> true
  * nil    ctxErr   + DeadlineExceeded-classified err -> true
  * nil    ctxErr   + Unavailable "client disconnected" -> true
  * nil    ctxErr   + Unavailable "stream error: ...; CANCEL" -> true
  * nil    ctxErr   + Unavailable with unrelated message -> false
  * nil    ctxErr   + Internal-classified err         -> false
  * nil    ctxErr   + plain (non-status) Go error      -> false
  * nil    ctxErr   + nil err                          -> false

Verification strategy
---------------------
L1 checks the deliverable files exist, are well-formed, and that the agent
actually authored a `TestIsClientCtxErr` (the doc's named deliverable) while
keeping the existing `TestGRPCError`.

L2 drives the repo's native Go toolchain. The discriminative L2 cases do NOT
trust the test file the agent itself may have written: this module copies an
*independent* probe test (`zz_isclientctx_probe_test.go`) into the `v3rpc`
package, which calls the unexported `isClientCtxErr` directly and
deep-validates the boolean result for every requirement (including the
boundary/error cases the doc says a naive implementation must fail). A stub
that ignores the second argument, only checks `ctxErr`, string-matches the
raw Go error text, or collapses every Unavailable error to true/false will
fail these probes. The doc's named native acceptance command
(`go test ./etcdserver/api/v3rpc/ -run TestIsClientCtxErr -count=1 -v`) is
also driven against the agent's own test.
"""

import os
import subprocess
import textwrap

import pytest

def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/etcd")
PKG_REL = "etcdserver/api/v3rpc"
SERVER_DIR = os.path.join(REPO_DIR, "server")
PKG_DIR = os.path.join(SERVER_DIR, PKG_REL)
UTIL_GO = os.path.join(PKG_DIR, "util.go")
UTIL_TEST_GO = os.path.join(PKG_DIR, "util_test.go")

PROBE_BASENAME = "zz_isclientctx_probe_test.go"
PROBE_PATH = os.path.join(PKG_DIR, PROBE_BASENAME)

GO_ENV = {
    **os.environ,
    "GOFLAGS": os.environ.get("GOFLAGS", ""),
    "CGO_ENABLED": "0",
}


def _go(args, timeout=600):
    """Run a `go` command from the server module dir."""
    return subprocess.run(
        ["go"] + args,
        cwd=SERVER_DIR,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=GO_ENV,
    )


# --------------------------------------------------------------------------
# Independent probe test installed into the package.
#
# It lives in `package v3rpc` so it can call the unexported `isClientCtxErr`.
# Each requirement is a hard subtest; the whole thing must compile AND pass.
# The probe deliberately rebuilds the exact error fixtures the doc describes
# (status.Error with codes, plain errors.New) so a naive implementation that
# only inspects ctxErr, or string-matches arbitrary Go error text, fails.
# --------------------------------------------------------------------------
PROBE_SOURCE = textwrap.dedent(
    '''\
    // Code generated by the skill benchmark. DO NOT keep.
    package v3rpc

    import (
    	stderrors "errors"
    	"testing"

    	"google.golang.org/grpc/codes"
    	"google.golang.org/grpc/status"
    )

    // SKILLPROBE A: a non-nil context error must force a `true` result,
    // regardless of the second argument (including nil and a clearly
    // server-internal error). A stub that only looks at the second arg fails.
    func TestSkillProbe_CtxErrForcesTrue(t *testing.T) {
    	cases := []error{
    		nil,
    		stderrors.New("anything"),
    		status.Error(codes.Internal, "server boom"),
    		status.Error(codes.Canceled, "context canceled"),
    	}
    	ctxErr := stderrors.New("server-side context already cancelled")
    	for i, e := range cases {
    		if got := isClientCtxErr(ctxErr, e); got != true {
    			t.Fatalf("case %d: isClientCtxErr(non-nil, %v) = %v, want true", i, e, got)
    		}
    	}
    }

    // SKILLPROBE B: with nil ctxErr, a Canceled- or DeadlineExceeded-classified
    // transport error must yield true.
    func TestSkillProbe_CancelAndDeadlineTrue(t *testing.T) {
    	if got := isClientCtxErr(nil, status.Error(codes.Canceled, "context canceled")); got != true {
    		t.Fatalf("nil ctx + Canceled status = %v, want true", got)
    	}
    	if got := isClientCtxErr(nil, status.Error(codes.DeadlineExceeded, "context deadline exceeded")); got != true {
    		t.Fatalf("nil ctx + DeadlineExceeded status = %v, want true", got)
    	}
    }

    // SKILLPROBE C: with nil ctxErr, an Unavailable error whose message is exactly
    // the client-disconnect message must yield true.
    func TestSkillProbe_UnavailableClientDisconnectedTrue(t *testing.T) {
    	if got := isClientCtxErr(nil, status.Error(codes.Unavailable, "client disconnected")); got != true {
    		t.Fatalf("nil ctx + Unavailable 'client disconnected' = %v, want true", got)
    	}
    }

    // SKILLPROBE D: with nil ctxErr, an Unavailable error whose message matches the
    // cancelled-stream pattern (prefix "stream error: " + suffix "; CANCEL") -> true.
    func TestSkillProbe_UnavailableStreamCancelTrue(t *testing.T) {
    	msg := "stream error: stream ID 21; CANCEL"
    	if got := isClientCtxErr(nil, status.Error(codes.Unavailable, msg)); got != true {
    		t.Fatalf("nil ctx + Unavailable %q = %v, want true", msg, got)
    	}
    }

    // SKILLPROBE E (negative / discriminative): an Unavailable error with an
    // UNRELATED message must yield false. A stub that returns true for every
    // Unavailable error fails here. Also exercises near-miss messages that share
    // only the prefix or only the suffix.
    func TestSkillProbe_UnavailableUnrelatedFalse(t *testing.T) {
    	bad := []string{
    		"connection refused",
    		"transport is closing",
    		"stream error: stream ID 7; PROTOCOL_ERROR", // prefix only
    		"some other thing; CANCEL",                   // suffix only
    		"",
    	}
    	for _, m := range bad {
    		if got := isClientCtxErr(nil, status.Error(codes.Unavailable, m)); got != false {
    			t.Fatalf("nil ctx + Unavailable %q = %v, want false", m, got)
    		}
    	}
    }

    // SKILLPROBE F (negative): a server-internal classification must yield false.
    func TestSkillProbe_InternalFalse(t *testing.T) {
    	for _, c := range []codes.Code{codes.Internal, codes.Unknown, codes.NotFound, codes.PermissionDenied, codes.ResourceExhausted} {
    		if got := isClientCtxErr(nil, status.Error(c, "server-side: "+c.String())); got != false {
    			t.Fatalf("nil ctx + %v status = %v, want false", c, got)
    		}
    	}
    }

    // SKILLPROBE G (negative): a plain non-transport Go error must yield false,
    // even if its text happens to look like a cancel message. The decision must
    // come from the transport classification, not raw string matching.
    func TestSkillProbe_PlainErrorFalse(t *testing.T) {
    	for _, e := range []error{
    		stderrors.New("totally unrelated boom"),
    		stderrors.New("client disconnected"),                  // same text, but no status
    		stderrors.New("stream error: stream ID 9; CANCEL"),    // same pattern, but no status
    		stderrors.New("context canceled"),
    	} {
    		if got := isClientCtxErr(nil, e); got != false {
    			t.Fatalf("nil ctx + plain error %q = %v, want false", e, got)
    		}
    	}
    }

    // SKILLPROBE H (boundary): nil err together with nil ctxErr must yield false.
    func TestSkillProbe_BothNilFalse(t *testing.T) {
    	if got := isClientCtxErr(nil, nil); got != false {
    		t.Fatalf("isClientCtxErr(nil, nil) = %v, want false", got)
    	}
    }
    '''
)


@pytest.fixture(scope="module", autouse=True)
def _install_probe_and_cleanup():
    """Install the independent probe test into the package, remove afterwards."""
    assert os.path.isdir(PKG_DIR), f"package dir missing: {PKG_DIR}"
    with open(PROBE_PATH, "w") as fh:
        fh.write(PROBE_SOURCE)
    try:
        yield
    finally:
        try:
            os.remove(PROBE_PATH)
        except OSError:
            pass


class TestGrpcServiceDefinition:
    REPO_DIR = _find_repo_dir("/workspace/etcd")

    # ---------------------- L1: deliverables exist / well-formed -------------

    def test_util_go_exists(self):
        """L1: the source file `util.go` exists."""
        assert os.path.isfile(UTIL_GO), f"missing {UTIL_GO}"

    def test_util_test_go_exists(self):
        """L1: the test file `util_test.go` exists."""
        assert os.path.isfile(UTIL_TEST_GO), f"missing {UTIL_TEST_GO}"

    def test_util_go_defines_isclientctxerr(self):
        """L1: `util.go` still defines the `isClientCtxErr` helper."""
        with open(UTIL_GO) as fh:
            src = fh.read()
        assert "func isClientCtxErr(" in src, "isClientCtxErr definition not found in util.go"

    def test_util_test_defines_isclientctxerr_test(self):
        """L1: the agent added the named `TestIsClientCtxErr` deliverable.

        The doc names this test explicitly; it must coexist with TestGRPCError.
        """
        with open(UTIL_TEST_GO) as fh:
            src = fh.read()
        assert "func TestIsClientCtxErr(" in src, (
            "TestIsClientCtxErr not found in util_test.go (the named deliverable)"
        )
        assert "func TestGRPCError(" in src, (
            "TestGRPCError disappeared from util_test.go (existing test must remain)"
        )

    def test_util_test_uses_status_and_codes(self):
        """L1: the agent's new test builds errors with grpc status/codes (not strings).

        The acceptance criteria require constructing errors with
        `google.golang.org/grpc/status` + `codes` and a plain `errors.New`.
        """
        with open(UTIL_TEST_GO) as fh:
            src = fh.read()
        assert "google.golang.org/grpc/status" in src, "status import missing in util_test.go"
        assert "google.golang.org/grpc/codes" in src, "codes import missing in util_test.go"

    # ---------------------- L2: native build + behavior ----------------------

    def test_package_builds(self):
        """L2: the v3rpc package compiles (agent did not break the build)."""
        res = _go(["build", "./" + PKG_REL + "/..."])
