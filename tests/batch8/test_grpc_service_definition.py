"""Tests for the `grpc-service-definition` skill (variant ext8).

Skill / task: Validate the server-streaming Watch *fragmentation* path in
etcd's v3 RPC server. `sendFragments` (in
`server/etcdserver/api/v3rpc/watch.go`) splits a `*pb.WatchResponse` that is
too large for a single transport message into an ordered sequence of smaller
messages. The behavioral contract that MUST hold:

  * a response that fits under the limit, or has fewer than two events, is
    emitted as exactly ONE message and that message carries the original
    (non-fragment) flag (`Fragment == false`);
  * when fragmentation occurs, concatenating the `Events` of the emitted
    messages in order reproduces the original event sequence exactly -- same
    count, same order, no duplication, no loss;
  * in a fragmented sequence every emitted message EXCEPT the last has its
    fragment flag set, and the last message has it cleared;
  * a single event larger than the limit is still emitted on its own (forward
    progress is guaranteed);
  * the send callback returning no error implies `sendFragments` returns nil;
  * the existing `TestSendFragment` keeps passing.

Verification strategy
---------------------
L1 checks the deliverable files (`watch.go`, `watch_test.go`) exist and are
minimally well-formed (still define `sendFragments` / `TestSendFragment`).

L2 drives the repo's native Go toolchain. The discriminative L2 cases do NOT
trust test files the agent itself may have written: this module copies an
*independent* probe test (`zz_skillprobe_fragments_test.go`) into the `v3rpc`
package. Because it lives in `package v3rpc` it can call the unexported
`sendFragments` directly. It builds `*pb.WatchResponse` values whose events
carry per-index unique keys, captures every message handed to the callback,
and deep-validates ordering/equality across concatenated fragments, the
fragment-flag pattern (all-but-last true, last false), the single-message
case, the oversized-single-event forward-progress case, and a nil return.

A naive solution that merely edits the agent's own test, that drops/reorders
events, that marks the wrong message non-fragment, or that fails to make
forward progress on an oversized event, fails these probes.
"""

import os
import subprocess
import textwrap

import pytest

def _find_repo_dir(_fallback):
    """Repo clones to /workspace/<repo-name>, not /workspace/<skill-id>. Prefer the
    harness-provided SWE_REPO_DIR (authoritative); else discover the single real repo
    dir under /workspace; else the known fallback. Reading SWE_REPO_DIR avoids picking
    the wrong repo when a job's rootfs accumulated several repos."""
    _env = os.environ.get("SWE_REPO_DIR")
    if _env and os.path.isdir(_env):
        return _env
    import glob as _glob
    _skip = {"tests", "benchmark_tests", "lost+found"}
    _c = [d for d in sorted(_glob.glob("/workspace/*"))
          if os.path.isdir(d) and os.path.basename(d) not in _skip]
    _git = [d for d in _c if os.path.isdir(os.path.join(d, ".git"))]
    if len(_git) == 1:
        return _git[0]
    if len(_c) == 1:
        return _c[0]
    return _fallback
REPO_DIR = _find_repo_dir("/workspace/etcd")
PKG_REL = "etcdserver/api/v3rpc"
SERVER_DIR = os.path.join(REPO_DIR, "server")
PKG_DIR = os.path.join(SERVER_DIR, PKG_REL)
WATCH_GO = os.path.join(PKG_DIR, "watch.go")
WATCH_TEST_GO = os.path.join(PKG_DIR, "watch_test.go")

PROBE_BASENAME = "zz_skillprobe_fragments_test.go"
PROBE_PATH = os.path.join(PKG_DIR, PROBE_BASENAME)

GO_ENV = {
    **os.environ,
    "GOFLAGS": os.environ.get("GOFLAGS", ""),
    "CGO_ENABLED": "0",
}


def _go(args, timeout=600):
    """Run a `go` command from the server module dir."""
    return subprocess.run(
        ["go"] + args,
        cwd=SERVER_DIR,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=GO_ENV,
    )


# --------------------------------------------------------------------------
# Independent probe test installed into the package.
#
# It lives in `package v3rpc` so it can call the unexported `sendFragments`.
# Every requirement is a hard assertion; the whole file must compile AND pass.
#
# Events are built with a per-index unique key (`fmt.Sprintf` of the index plus
# padding) so we can verify exact ordering / no-duplication / no-loss across the
# concatenated fragments -- not just the message count.
# --------------------------------------------------------------------------
PROBE_SOURCE = textwrap.dedent(
    '''\
    // Code generated by the skill benchmark. DO NOT keep.
    package v3rpc

    import (
    	"bytes"
    	"fmt"
    	"math"
    	"testing"

    	pb "go.etcd.io/etcd/api/v3/etcdserverpb"
    	"go.etcd.io/etcd/api/v3/mvccpb"
    )

    // skillUniqueResponse builds a WatchResponse with `events` events. Each
    // event gets a key that is unique per index (an index marker followed by
    // `pad` filler bytes) so we can verify exact ordering after fragmentation.
    func skillUniqueResponse(events, pad int) *pb.WatchResponse {
    	resp := &pb.WatchResponse{Events: make([]*mvccpb.Event, events)}
    	for i := range resp.Events {
    		key := append([]byte(fmt.Sprintf("k%08d-", i)), bytes.Repeat([]byte("a"), pad)...)
    		resp.Events[i] = &mvccpb.Event{
    			Kv: &mvccpb.KeyValue{Key: key},
    		}
    	}
    	return resp
    }

    // skillCapture runs sendFragments and returns the emitted messages.
    func skillCapture(t *testing.T, wr *pb.WatchResponse, maxBytes uint) []*pb.WatchResponse {
    	t.Helper()
    	captured := make([]*pb.WatchResponse, 0)
    	send := func(r *pb.WatchResponse) error {
    		// Defensively snapshot the events slice; the production code reuses
    		// a value receiver but we must not depend on aliasing semantics.
    		cp := *r
    		cp.Events = append([]*mvccpb.Event(nil), r.Events...)
    		captured = append(captured, &cp)
    		return nil
    	}
    	if err := sendFragments(wr, maxBytes, send); err != nil {
    		t.Fatalf("sendFragments returned non-nil error: %v", err)
    	}
    	if len(captured) == 0 {
    		t.Fatalf("sendFragments emitted zero messages")
    	}
    	return captured
    }

    // skillConcat flattens the events of an emitted message sequence in order.
    func skillConcat(msgs []*pb.WatchResponse) []*mvccpb.Event {
    	out := make([]*mvccpb.Event, 0)
    	for _, m := range msgs {
    		out = append(out, m.Events...)
    	}
    	return out
    }

    // skillAssertFlags checks the all-but-last-true / last-false fragment pattern.
    func skillAssertFlags(t *testing.T, msgs []*pb.WatchResponse) {
    	t.Helper()
    	n := len(msgs)
    	for i := 0; i < n-1; i++ {
    		if !msgs[i].Fragment {
    			t.Fatalf("message %d/%d expected Fragment=true, got false", i, n)
    		}
    	}
    	if msgs[n-1].Fragment {
    		t.Fatalf("last message (%d) expected Fragment=false, got true", n-1)
    	}
    }

    // skillAssertOrder checks concatenated events equal the original sequence
    // exactly (same count, same order, identity-by-key, no dup, no loss).
    func skillAssertOrder(t *testing.T, original *pb.WatchResponse, msgs []*pb.WatchResponse) {
    	t.Helper()
    	got := skillConcat(msgs)
    	if len(got) != len(original.Events) {
    		t.Fatalf("concatenated event count = %d, want %d", len(got), len(original.Events))
    	}
    	for i := range original.Events {
    		wantKey := original.Events[i].Kv.Key
    		gotKey := got[i].Kv.Key
    		if !bytes.Equal(gotKey, wantKey) {
    			t.Fatalf("event %d out of order/changed: got key %q, want %q", i, gotKey, wantKey)
    		}
    	}
    }

    // SKILLPROBE A: small response (fits under limit) -> exactly one message,
    // Fragment flag false.
    func TestSkillFrag_SmallFitsOneMessage(t *testing.T) {
    	wr := skillUniqueResponse(5, 4)
    	msgs := skillCapture(t, wr, math.MaxInt32)
    	if len(msgs) != 1 {
    		t.Fatalf("fits-under-limit: emitted %d messages, want 1", len(msgs))
    	}
    	if msgs[0].Fragment {
    		t.Fatalf("fits-under-limit: single message must have Fragment=false")
    	}
    	skillAssertOrder(t, wr, msgs)
    }

    // SKILLPROBE B: fewer than two events -> exactly one message even if it
    // exceeds the limit, Fragment false (cannot fragment a single event here).
    func TestSkillFrag_FewerThanTwoEventsOneMessage(t *testing.T) {
    	// One large event, tiny limit.
    	wr := skillUniqueResponse(1, 1024)
    	msgs := skillCapture(t, wr, 1)
    	if len(msgs) != 1 {
    		t.Fatalf("single-event: emitted %d messages, want 1", len(msgs))
    	}
    	if msgs[0].Fragment {
    		t.Fatalf("single-event: message must have Fragment=false")
    	}
    	skillAssertOrder(t, wr, msgs)

    	// Zero events also yields exactly one (non-fragment) message.
    	wr0 := skillUniqueResponse(0, 0)
    	msgs0 := skillCapture(t, wr0, 1)
    	if len(msgs0) != 1 || msgs0[0].Fragment {
    		t.Fatalf("zero-event: want 1 non-fragment message, got %d (frag=%v)",
    			len(msgs0), msgs0[0].Fragment)
    	}
    }

    // SKILLPROBE C: large response of N events forced to fragment.
    //   - more than one message MUST be emitted;
    //   - concatenated events equal the original N in order;
    //   - all-but-last Fragment=true, last Fragment=false.
    func TestSkillFrag_LargeFragmentsOrderingAndFlags(t *testing.T) {
    	// 8 events, each ~16 bytes of key; tiny limit forces per-event fragments.
    	wr := skillUniqueResponse(8, 16)
    	msgs := skillCapture(t, wr, 8)
    	if len(msgs) < 2 {
    		t.Fatalf("expected fragmentation (>=2 messages), got %d", len(msgs))
    	}
    	skillAssertOrder(t, wr, msgs)
    	skillAssertFlags(t, msgs)
    }

    // SKILLPROBE C2: combined-only-exceeds case. Events individually fit but
    // pairs exceed the limit; ordering + flags must still hold and the original
    // sequence must be perfectly reconstructable.
    func TestSkillFrag_CombinedExceedsOrdering(t *testing.T) {
    	wr := skillUniqueResponse(6, 12)
    	msgs := skillCapture(t, wr, 30)
    	if len(msgs) < 2 {
    		t.Fatalf("expected fragmentation (>=2 messages), got %d", len(msgs))
    	}
    	skillAssertOrder(t, wr, msgs)
    	skillAssertFlags(t, msgs)
    	// No emitted message (except possibly trivial boundaries) should be empty
    	// while there is still ordering to reproduce: every event accounted for.
    	total := 0
    	for _, m := range msgs {
    		total += len(m.Events)
    	}
    	if total != len(wr.Events) {
    		t.Fatalf("event accounting mismatch: emitted %d, want %d", total, len(wr.Events))
    	}
    }

    // SKILLPROBE D: one oversized event among several -> still emitted, ordering
    // preserved, forward progress guaranteed (no infinite loop / no dropped events).
    func TestSkillFrag_OversizedEventForwardProgress(t *testing.T) {
    	wr := &pb.WatchResponse{Events: make([]*mvccpb.Event, 4)}
    	// indices 0,2,3 are small; index 1 is huge (alone exceeds the limit).
    	for i := range wr.Events {
    		pad := 4
    		if i == 1 {
    			pad = 4096
    		}
    		key := append([]byte(fmt.Sprintf("k%08d-", i)), bytes.Repeat([]byte("a"), pad)...)
    		wr.Events[i] = &mvccpb.Event{Kv: &mvccpb.KeyValue{Key: key}}
    	}
    	msgs := skillCapture(t, wr, 64)
    	skillAssertOrder(t, wr, msgs)
    	skillAssertFlags(t, msgs)
    	// The oversized event (index 1) must appear exactly once somewhere.
    	concat := skillConcat(msgs)
    	if len(concat) != 4 {
    		t.Fatalf("oversized case: got %d events total, want 4", len(concat))
    	}
    }

    // SKILLPROBE E: callback returning nil -> sendFragments returns nil.
    func TestSkillFrag_NilReturnOnSuccess(t *testing.T) {
    	wr := skillUniqueResponse(7, 16)
    	err := sendFragments(wr, 8, func(*pb.WatchResponse) error { return nil })
    	if err != nil {
    		t.Fatalf("sendFragments with always-nil callback returned %v, want nil", err)
    	}
    }

    // SKILLPROBE F: exactly one non-fragment terminator. In any emitted sequence
    // there must be precisely one message with Fragment=false and it must be last.
    func TestSkillFrag_ExactlyOneTerminator(t *testing.T) {
    	for _, tc := range []struct {
    		events, pad int
    		maxBytes    uint
    	}{
    		{8, 16, 8},
    		{6, 12, 30},
    		{5, 11, 20},
    		{4, 10, 35},
    	} {
    		wr := skillUniqueResponse(tc.events, tc.pad)
    		msgs := skillCapture(t, wr, tc.maxBytes)
    		nonFrag := 0
    		lastIdx := -1
    		for i, m := range msgs {
    			if !m.Fragment {
    				nonFrag++
    				lastIdx = i
    			}
    		}
    		if nonFrag != 1 {
    			t.Fatalf("events=%d max=%d: %d non-fragment messages, want exactly 1",
    				tc.events, tc.maxBytes, nonFrag)
    		}
    		if lastIdx != len(msgs)-1 {
    			t.Fatalf("events=%d max=%d: terminator at %d, want last (%d)",
    				tc.events, tc.maxBytes, lastIdx, len(msgs)-1)
    		}
    		skillAssertOrder(t, wr, msgs)
    	}
    }
    '''
)


@pytest.fixture(scope="module", autouse=True)
def _install_probe_and_cleanup():
    """Install the independent probe test into the package, remove afterwards."""
    assert os.path.isdir(PKG_DIR), f"package dir missing: {PKG_DIR}"
    with open(PROBE_PATH, "w") as fh:
        fh.write(PROBE_SOURCE)
    try:
        yield
    finally:
        try:
            os.remove(PROBE_PATH)
        except OSError:
            pass


class TestGrpcServiceDefinition:
    REPO_DIR = _find_repo_dir("/workspace/etcd")

    # ---------------------- L1: deliverables exist / well-formed -------------

    def test_watch_go_exists(self):
        """L1: the production source file `watch.go` exists."""
        assert os.path.isfile(WATCH_GO), f"missing {WATCH_GO}"

    def test_watch_test_go_exists(self):
        """L1: the test file `watch_test.go` exists."""
        assert os.path.isfile(WATCH_TEST_GO), f"missing {WATCH_TEST_GO}"

    def test_watch_go_defines_sendfragments(self):
        """L1: `watch.go` still defines `sendFragments` (the function under test)."""
        with open(WATCH_GO) as fh:
            src = fh.read()
        assert "func sendFragments(" in src, "sendFragments definition not found in watch.go"
        # the fragment flag plumbing must remain present
        assert "Fragment" in src, "Fragment flag handling not found in watch.go"

    def test_watch_test_defines_sendfragment_test(self):
        """L1: `watch_test.go` still contains the canonical `TestSendFragment`."""
        with open(WATCH_TEST_GO) as fh:
            src = fh.read()
        assert "func TestSendFragment(" in src, "TestSendFragment not found in watch_test.go"

    def test_watch_test_has_ordering_complement(self):
        """L1: a complementary ordering test (e.g. TestSendFragmentsOrdering) was added.

        Per the doc, the agent must add a test that complements TestSendFragment by
        checking ordering/flags, not just count. We do not trust its assertions
        (the L2 probe does the real validation) -- this is only a deliverable check
        that a *distinct* new test function exists in the file.
        """
        with open(WATCH_TEST_GO) as fh:
            src = fh.read()
        # any new top-level test function beyond the original two helpers/tests.
        new_tests = [
            line
            for line in src.splitlines()
            if line.startswith("func Test")
            and "func TestSendFragment(" not in line
        ]
        assert new_tests, (
            "no complementary Test* function (e.g. TestSendFragmentsOrdering) "
            "found in watch_test.go beyond the original TestSendFragment"
        )

    # ---------------------- L2: native build + behavior ----------------------

    def test_package_builds(self):
        """L2: the v3rpc package compiles (agent did not break the build)."""
        res = _go(["build", "./" + PKG_REL + "/..."])
        assert res.returncode == 0, (
            "go build failed:\n" + res.stdout + "\n" + res.stderr
        )

    def test_vet_package(self):
        """L2: `go vet` passes on the package when it is able to run."""
        res = _go(["vet", "./" + PKG_REL + "/"])
        if res.returncode != 0:
            combined = (res.stdout + res.stderr).lower()
            if (
                "cannot find" not in combined
                and "timeout" not in combined
                and "dial tcp" not in combined
                and "no such host" not in combined
            ):
                assert res.returncode == 0, (
                    "go vet reported problems:\n" + res.stdout + "\n" + res.stderr
                )

    def test_existing_sendfragment_passes(self):
        """L2: the canonical, unchanged `TestSendFragment` must still pass."""
        res = _go(
            ["test", "./" + PKG_REL + "/", "-run", "^TestSendFragment$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, "TestSendFragment failed:\n" + out
        assert "PASS" in out or "ok  " in out, "no PASS marker:\n" + out
        assert "--- FAIL" not in out, "a subtest FAILED:\n" + out

    def test_probe_small_and_single_event(self):
        """L2: small/fits and <2-event responses emit one non-fragment message."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillFrag_SmallFitsOneMessage|TestSkillFrag_FewerThanTwoEventsOneMessage)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "small/single-event probe failed (one non-fragment message expected):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_large_ordering_and_flags(self):
        """L2: forced fragmentation preserves order and the all-but-last-true flag pattern."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillFrag_LargeFragmentsOrderingAndFlags|TestSkillFrag_CombinedExceedsOrdering)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "fragmentation ordering/flags probe failed (events reordered/dropped or "
            "wrong message marked non-fragment):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_oversized_event_forward_progress(self):
        """L2: an oversized single event among several is still emitted, order preserved."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^TestSkillFrag_OversizedEventForwardProgress$", "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "oversized-event probe failed (forward progress not guaranteed / "
            "event dropped or reordered):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_probe_nil_return_and_terminator(self):
        """L2: nil return on success, and exactly one terminator (last, Fragment=false)."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSkillFrag_NilReturnOnSuccess|TestSkillFrag_ExactlyOneTerminator)$",
             "-count=1", "-v"],
            timeout=600,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "nil-return/terminator probe failed (non-nil return on success, or the "
            "fragment terminator is missing/duplicated/misplaced):\n" + out
        )
        assert "--- FAIL" not in out, out

    def test_full_probe_suite_and_existing_pass_together(self):
        """L2: the whole fragmentation behavior matrix passes in one native run."""
        res = _go(
            ["test", "./" + PKG_REL + "/",
             "-run", "^(TestSendFragment|TestSkillFrag_.*)$", "-count=1", "-v"],
            timeout=900,
        )
        out = res.stdout + res.stderr
        assert res.returncode == 0, (
            "combined existing + probe suite failed:\n" + out
        )
        assert "--- FAIL" not in out, "at least one case FAILED:\n" + out
        assert "ok  " in out or "PASS" in out, "no success marker:\n" + out
